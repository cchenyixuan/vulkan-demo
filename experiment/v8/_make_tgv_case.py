"""
_make_tgv_case.py — write a two-dimensional Taylor–Green vortex case for experiment/v8.

Box [0, L)^2, doubly periodic, N x N fluid particles on a square lattice at ((i + 1/2) dx, (j + 1/2) dx),
dx = L / N, support radius h = (h/dx) dx (the project's h/dx = 5), no walls. U0, rho0 and L are 1 by default;
Re = U0 L / nu sets the material's kinematic viscosity, Ma = U0 / c0 the speed of sound (0.1 -> c0 = 10 U0, the
usual SPH choice). The numerics block is the cavity cases' (delta 0.1, KCG xi 0.001, eps^2 0.0025 h^2, PST
0.1 / 0.0005, CFL 0.15); --no-pst / --no-delta / --no-kcg switch the ablation toggles off.

    .venv/Scripts/python.exe experiment/v8/_make_tgv_case.py --side 200 --reynolds 100 --out cases/tgv_2d/re100_n200

Writes domain.obj (the lattice), frame.obj (the box; the loader takes the periodic span from it), materials.yaml
(the fluid material of this Re) and case.yaml. L / h = N / (h/dx) must be an integer >= 3.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import sys

import numpy as np

_REPOSITORY_ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(_REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPOSITORY_ROOT))

CASE_YAML = """\
schema_version: 2

# 2-D Taylor-Green vortex, {side} x {side} = {count:,} fluid particles on [0, {length:g})^2, doubly periodic.
# GENERATED by experiment/v8/_make_tgv_case.py {command_line}
# dx = {dx:.8g}, h = {h:.8g} (h/dx = {hdx:g}), L/h = {voxels} voxels per side.
# U0 = {amplitude:g}, rho0 = {rest_density:g}, nu = {viscosity:.8g} (Re = {reynolds:g}), c0 = {speed_of_sound:g} (Ma = {mach:g}),
# dt = CFL h / c0 = {timestep:.8g}; F(t) = exp(-{decay_rate:.8g} t).{viscous_note}

time:
  total: {t_end:g}
  max_steps: null
  output_cadence: null

physics:
  dimension: 2
  periodic: [true, true]
  h: {h:.8g}
  particle_radius: {particle_radius:.8g}
  lattice: grid
  calibrate_volume: true
  speed_of_sound: {speed_of_sound:g}
  power: 7
  cfl: {cfl:.6g}
  gravity: [0.0, 0.0, 0.0]

initial_field:
  type: taylor_green
  amplitude: {amplitude:g}
  vortex_pairs: 1
  origin_offset: [{origin_offset:g}, {origin_offset:g}]
  density_from_pressure: {density_from_pressure}

numerics:
  use_density_diffusion: {use_delta}
  delta_coefficient: 0.1
  use_kcg_correction: {use_kcg}
  regularization:
    xi: 0.001
    det_threshold: 1.0e-4
    frobenius_max: 10.0
  epsilon_squared_factor: {epsilon_squared_factor:g}
  use_pst: {use_pst}
  pst_main: 0.1
  pst_anti: 0.0005
  defrag_enabled: true
  defrag_cadence: 1000
  use_prefix_sum_defrag: false

capacities:
  pool_size: {pool_size}
  max_per_voxel: {max_per_voxel}
  max_incoming: 16
  workgroup: 128

material_library: materials.yaml

geometry:
  frame: frame.obj
  particles:
    - {{file: domain.obj, material: tgv_fluid}}
"""

MATERIALS_YAML = """\
schema_version: 1

# GENERATED by experiment/v8/_make_tgv_case.py: the fluid of this Taylor-Green case.
tgv_fluid:
  kind: fluid
  rest_density: {rest_density:g}
  viscosity: {viscosity:.10g}      # kinematic, = U0 L / Re
"""


def write_frame_obj(path: pathlib.Path, length: float, z_half: float) -> None:
    vertices = [(0.0, 0.0, -z_half), (0.0, length, -z_half), (length, 0.0, -z_half), (length, length, -z_half),
                (0.0, 0.0, z_half), (0.0, length, z_half), (length, 0.0, z_half), (length, length, z_half)]
    faces = [(1, 2, 4), (1, 4, 3), (5, 7, 8), (5, 8, 6), (1, 5, 6), (1, 6, 2),
             (3, 4, 8), (3, 8, 7), (1, 3, 7), (1, 7, 5), (2, 6, 8), (2, 8, 4)]
    with path.open("w", encoding="utf-8") as handle:
        handle.write("# Taylor-Green periodic box\n")
        for vertex in vertices:
            handle.write(f"v {vertex[0]:.9g} {vertex[1]:.9g} {vertex[2]:.9g}\n")
        for face in faces:
            handle.write(f"f {face[0]} {face[1]} {face[2]}\n")


def build(arguments: argparse.Namespace, command_line: str) -> pathlib.Path:
    side = int(arguments.side)
    length = float(arguments.length)
    hdx = float(arguments.hdx)
    dx = length / side
    h = hdx * dx
    voxels = side / hdx
    if abs(voxels - round(voxels)) > 1e-9 or round(voxels) < 3:
        raise SystemExit(f"--side {side} / --hdx {hdx:g} = {voxels} must be an integer >= 3 (the periodic box tiles "
                         "the voxel grid)")
    voxels = int(round(voxels))
    amplitude = float(arguments.amplitude)
    viscosity = amplitude * length / float(arguments.reynolds)
    speed_of_sound = amplitude / float(arguments.mach)
    # The loader's dt = cfl h / c0 is the acoustic limit only. The explicit viscous operator needs
    # dt <= viscous_factor h^2 / nu as well (measured on 800^2 at Re 100: cfl 0.1 and 0.125 (0.016, 0.020 h^2 / nu) stable, 0.15 (0.024) blows up in
    # the first 400 steps, i.e. the threshold is 0.020-0.024 h^2 / nu; the default 0.0125 keeps a 1.6x margin); where the viscous limit is the smaller one
    # the written cfl is lowered to meet it and the header says so.
    cfl = float(arguments.cfl)
    timestep_acoustic = cfl * h / speed_of_sound
    timestep_viscous = float(arguments.viscous_factor) * h * h / viscosity if viscosity > 0 else math.inf
    viscous_note = ""
    if timestep_viscous < timestep_acoustic:
        cfl = cfl * timestep_viscous / timestep_acoustic
        viscous_note = (chr(10) + f"# VISCOUS LIMIT: dt = {timestep_viscous:.8g} = {float(arguments.viscous_factor):g} h^2 / nu "
                        + f"< the acoustic {timestep_acoustic:.8g} (cfl {float(arguments.cfl):g}): cfl written as {cfl:.6g}.")
    timestep = cfl * h / speed_of_sound
    k = 2.0 * math.pi / length
    count = side * side
    pool_size = int(math.ceil(count * 1.15 / 128) * 128)
    # a voxel of side h holds (h/dx)^2 lattice particles; PST keeps the packing near the lattice
    max_per_voxel = int(max(64, math.ceil(2.5 * hdx * hdx / 32) * 32))

    out_dir = (_REPOSITORY_ROOT / arguments.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    index = np.arange(side, dtype=np.float64) + 0.5
    x, y = np.meshgrid(index * dx, index * dx, indexing="ij")
    points = np.column_stack([x.ravel(), y.ravel(), np.zeros(count)])
    np.savetxt(out_dir / "domain.obj", points, fmt="v %.9g %.9g %.9g", header=f"# {count} particles", comments="")
    write_frame_obj(out_dir / "frame.obj", length, 0.5 * dx)
    (out_dir / "materials.yaml").write_text(
        MATERIALS_YAML.format(rest_density=float(arguments.rest_density), viscosity=viscosity), encoding="utf-8")
    (out_dir / "case.yaml").write_text(CASE_YAML.format(
        side=side, count=count, length=length, command_line=command_line, dx=dx, h=h, hdx=hdx, voxels=voxels,
        amplitude=amplitude, rest_density=float(arguments.rest_density), viscosity=viscosity,
        reynolds=float(arguments.reynolds), speed_of_sound=speed_of_sound, mach=float(arguments.mach),
        timestep=timestep, decay_rate=2.0 * viscosity * k * k, t_end=float(arguments.t_end),
        particle_radius=0.5 * dx, cfl=cfl, viscous_note=viscous_note,
        density_from_pressure="true" if not arguments.uniform_density else "false",
        origin_offset=float(arguments.origin_offset),
        use_delta="false" if arguments.no_delta else "true", use_kcg="false" if arguments.no_kcg else "true",
        use_pst="false" if arguments.no_pst else "true", pool_size=pool_size, max_per_voxel=max_per_voxel,
        epsilon_squared_factor=float(arguments.epsilon_squared_factor)),
        encoding="utf-8")
    print(f"[tgv] {out_dir}: {side}x{side} = {count:,} particles, dx={dx:.6g} h={h:.6g} grid {voxels}^2, "
          f"Re={float(arguments.reynolds):g} nu={viscosity:.6g} c0={speed_of_sound:g} dt={timestep:.6g}"
          f"{' (viscous limit, cfl ' + format(cfl, '.4g') + ')' if viscous_note else ''} "
          f"steps to t={float(arguments.t_end):g}: {math.ceil(float(arguments.t_end) / timestep):,}")
    return out_dir


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    result.add_argument("--side", type=int, required=True, help="particles per side N (L/dx)")
    result.add_argument("--reynolds", type=float, default=100.0)
    result.add_argument("--mach", type=float, default=0.1, help="U0 / c0 (0.1 -> c0 = 10 U0)")
    result.add_argument("--hdx", type=float, default=5.0, help="support radius over spacing")
    result.add_argument("--cfl", type=float, default=0.15)
    result.add_argument("--epsilon-squared-factor", type=float, default=0.0025,
                        help="eps^2 = this * h^2 in the viscous and delta-diffusion denominators (case default 0.0025)")
    result.add_argument("--viscous-factor", type=float, default=0.0125,
                        help="dt <= this * h^2 / nu (support radius h); the cfl is lowered when this limit binds")
    result.add_argument("--length", type=float, default=1.0)
    result.add_argument("--amplitude", type=float, default=1.0)
    result.add_argument("--rest-density", type=float, default=1.0)
    result.add_argument("--t-end", type=float, default=2.0, help="recorded in time.total (informational)")
    result.add_argument("--uniform-density", action="store_true", help="rho0 everywhere instead of rho(p(x, 0))")
    result.add_argument("--origin-offset", type=float, default=0.25,
                        help="field origin at this fraction of L from the box corner (0.25: the fastest streams "
                             "cross the periodic edges; 0: nothing crosses)")
    result.add_argument("--no-pst", action="store_true")
    result.add_argument("--no-delta", action="store_true")
    result.add_argument("--no-kcg", action="store_true")
    result.add_argument("--out", required=True)
    return result


def main() -> int:
    arguments = parser().parse_args()
    build(arguments, " ".join(sys.argv[1:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
