"""
_run_weak_scaling_campaign.py — VGPU weak-scaling sweep: CONSTANT work per slab.

Motivation (user, 2026-07-22): the earlier fixed-total-N K-sweeps conflate two
effects — per-slab compute shrinks with K (shrinking the Phase B hiding
window) while per-link transport stays constant, so "period linear in K"
mixes real coordination growth with an artificial exposure effect. This
campaign holds PER-SLAB work constant (~2.0M particles per slab, identical
slab geometry) so period growth beyond ideal compute serialization is pure
exposed coordination cost.

Case family: cases/cavity_weak_k{K}_*  — stretched lid-driven cavity, height
fixed 1 m, width proportional to K, identical dx (generated by
utils/geometry/_demo_cavity_case.py --half 707 --half-x 707*K). Per-slab
fluid count 2,002,225..2,002,932 (spread < 0.04%).

Matrix:
  solo_d{0,1}            single bench on the K=1 case (T_solo reference,
                         both devices: dev0 carries the Windows desktop)
  chain1_k{2,3,4}_d{0,1} single-PHYSICAL-card chains (all slabs one device)
  dual_k{2,4,6,8}        two-card chains, ABAB interleave (every link
                         crosses GPUs — faithful cluster emulation shape)

Matched pairs (equal per-GPU slab count, chain length doubles):
  chain1_k2 vs dual_k4   (2 slabs/GPU)
  chain1_k3 vs dual_k6   (3 slabs/GPU)
  chain1_k4 vs dual_k8   (4 slabs/GPU)

Headline metric: overhead(K) = steady_period_us - slabs_per_gpu * T_solo_us.

Provenance (2026-07-22 instruments-audit requirement): every point archives
full stdout+stderr, the exact command line, git HEAD, and the submit-lock /
validation-layer environment into logs/weak_scaling_20260722/. Summary rows
append to summary.jsonl immediately (crash leaves partial data).

Protocol: warmup 5000 + 20000 measured steps, per-direction sync scheme,
pool_safety 1.2 (chain default), chain depth 2 (default), validation OFF
(and explicitly disabled via loader env so an installed SDK cannot
re-enable it — feedback-dual-runner-validation-bench lesson).

    .venv/Scripts/python.exe experiment/v5/_run_weak_scaling_campaign.py
    .venv/Scripts/python.exe experiment/v5/_run_weak_scaling_campaign.py --only dual_k4
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import subprocess
import sys
import time

_REPO = pathlib.Path(__file__).resolve().parents[2]
_PYTHON = sys.executable   # same interpreter (portable: .venv/Scripts on Windows, .venv/bin on Linux)
_OUT_DIR = _REPO / "logs/weak_scaling_20260722"

_ENV = {
    **os.environ,
    "PYTHONIOENCODING": "utf-8",
    "VK_LOADER_LAYERS_DISABLE": "VK_LAYER_KHRONOS_validation",
    # Per-physical-GPU submit lock (the post-audit default; recorded per point
    # so the sweep's lock regime is never ambiguous again).
    "V5_SUBMIT_LOCK_SCOPE": os.environ.get("V5_SUBMIT_LOCK_SCOPE", "device"),
}

WARMUP = 5000
MAX_STEPS = 25000          # 20000 measured steps after warmup

_CASES = {
    1: "cases/cavity_weak_k1_2m/case.yaml",
    2: "cases/cavity_weak_k2_4m/case.yaml",
    3: "cases/cavity_weak_k3_6m/case.yaml",
    4: "cases/cavity_weak_k4_8m/case.yaml",
    6: "cases/cavity_weak_k6_12m/case.yaml",
    8: "cases/cavity_weak_k8_16m/case.yaml",
}


def _single_cmd(device: int) -> list[str]:
    return [_PYTHON, "experiment/v5/_run_v5_single_bench.py",
            "--case", _CASES[1], "--device", str(device),
            "--max-steps", str(MAX_STEPS), "--warmup", str(WARMUP),
            "--bench-window", str(MAX_STEPS - WARMUP)]


def _chain_cmd(slab_count: int, device_map: str) -> list[str]:
    return [_PYTHON, "experiment/v5/_run_v5_chain_bench.py",
            "--case", _CASES[slab_count],
            "--weights", ",".join(["1"] * slab_count),
            "--device-map", device_map,
            "--sync-scheme", "per-direction",
            "--max-steps", str(MAX_STEPS), "--warmup", str(WARMUP)]


# (name, command, slabs_per_gpu, devices_used) — cheap points first so an
# interrupted campaign still yields the matched-pair backbone.
POINTS: list[tuple[str, list[str], int, str]] = [
    ("solo_d0",      _single_cmd(0),                 1, "0"),
    ("solo_d1",      _single_cmd(1),                 1, "1"),
    ("dual_k2",      _chain_cmd(2, "0,1"),           1, "0,1"),
    ("chain1_k2_d0", _chain_cmd(2, "0,0"),           2, "0"),
    ("chain1_k2_d1", _chain_cmd(2, "1,1"),           2, "1"),
    ("dual_k4",      _chain_cmd(4, "0,1,0,1"),       2, "0,1"),
    ("chain1_k3_d0", _chain_cmd(3, "0,0,0"),         3, "0"),
    ("chain1_k3_d1", _chain_cmd(3, "1,1,1"),         3, "1"),
    ("dual_k6",      _chain_cmd(6, "0,1,0,1,0,1"),   3, "0,1"),
    ("chain1_k4_d0", _chain_cmd(4, "0,0,0,0"),       4, "0"),
    ("chain1_k4_d1", _chain_cmd(4, "1,1,1,1"),       4, "1"),
    ("dual_k8",      _chain_cmd(8, "0,1,0,1,0,1,0,1"), 4, "0,1"),
]

_STEADY_RE = re.compile(
    r"\[chain_v5\] STEADY \(post-warmup \d+\): (\d+) steps in ([\d.]+)s = ([\d.]+) fps")
_DRIFT_RE = re.compile(r"\[chain_v5\] final: total=[\d,]+ \(expected [\d,]+\) drift=(-?\d+)")
_WINDOW_RE = re.compile(r"frame_total_us\s+mean=\s*([\d.]+)us\s+p50=\s*([\d.]+)us")


def _git_head() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=_REPO,
                              capture_output=True, text=True).stdout.strip()
    except OSError:
        return "unknown"


def _parse(name: str, output: str) -> dict:
    row: dict = {}
    if name.startswith("solo"):
        # Last (only) full window aggregate over the 20000 post-warmup frames.
        windows = _WINDOW_RE.findall(output)
        if windows:
            mean_us, p50_us = (float(v) for v in windows[-1])
            row.update(frame_mean_us=mean_us, frame_p50_us=p50_us,
                       steady_fps=round(1e6 / mean_us, 1))
        if "WARN: alive drift" in output:
            row["drift_warning"] = True
    else:
        steady = _STEADY_RE.search(output)
        if steady:
            steps, seconds, fps = steady.groups()
            row.update(steady_frames=int(steps), steady_s=float(seconds),
                       steady_fps=float(fps),
                       frame_mean_us=round(1e6 / float(fps), 1))
        drift = _DRIFT_RE.search(output)
        if drift:
            row["drift"] = int(drift.group(1))
        row["validation_failed"] = "*** VALIDATION FAILED ***" in output
    return row


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default=None,
                        help="comma-separated point names to (re-)run; default all")
    args = parser.parse_args()
    selected = set(args.only.split(",")) if args.only else None

    _OUT_DIR.mkdir(parents=True, exist_ok=True)
    summary_path = _OUT_DIR / "summary.jsonl"
    git_head = _git_head()

    for name, cmd, slabs_per_gpu, devices in POINTS:
        if selected is not None and name not in selected:
            continue
        log_path = _OUT_DIR / f"{name}.log"
        print(f"[campaign] {name}: {' '.join(cmd[1:])}", flush=True)
        t_start = time.time()
        result = subprocess.run(cmd, cwd=_REPO, env=_ENV,
                                capture_output=True, text=True,
                                encoding="utf-8", errors="replace")
        wall_s = round(time.time() - t_start, 1)
        output = (result.stdout or "") + (result.stderr or "")
        log_path.write_text(output, encoding="utf-8")

        row = {
            "point": name,
            "slabs_per_gpu": slabs_per_gpu,
            "devices": devices,
            "cmd": " ".join(cmd[1:]),
            "returncode": result.returncode,
            "wall_s": wall_s,
            "git_head": git_head,
            "submit_lock_scope": _ENV["V5_SUBMIT_LOCK_SCOPE"],
            "vk_loader_layers_disable": _ENV["VK_LOADER_LAYERS_DISABLE"],
            "warmup": WARMUP, "max_steps": MAX_STEPS,
            "log": str(log_path.relative_to(_REPO)),
            "t": round(time.time(), 1),
        }
        row.update(_parse(name, output))
        with open(summary_path, "a", encoding="utf-8") as handle:
            handle.write(json.dumps(row) + "\n")
        print(f"[campaign] {name}: rc={result.returncode} "
              f"steady_fps={row.get('steady_fps')} drift={row.get('drift')} "
              f"({wall_s}s)", flush=True)

    print(f"[campaign] done -> {summary_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
