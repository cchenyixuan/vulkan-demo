def _write_points(path: pathlib.Path, points: np.ndarray, comment: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"# {comment}\n")
        for x, y in points:
            handle.write(f"v {x:.9f} {y:.9f} 0.000000000\n")


def design_parameters(far_viscosity: float, coupling_ratio: float, micropolar_length: float) -> dict:
    """The solver's coefficients from nu_inf = (mu + kappa / 2) / rho, K = kappa / mu and l (Stage 3, section 5):
    mu / rho = nu_inf / (1 + K / 2), c = K mu / rho, nu = (1 + K) mu / rho, nu_t = -mu / rho,
    xi = l^2 c (2 nu - c) / nu, Theta = l^2."""
    shear = far_viscosity / (1.0 + 0.5 * coupling_ratio)
    coupling = coupling_ratio * shear
    viscosity = (1.0 + coupling_ratio) * shear
    return {"viscosity": viscosity, "viscosity_transfer": -shear, "coupling": coupling,
            "viscosity_rotation": micropolar_length ** 2 * coupling * (2.0 * viscosity - coupling) / viscosity,
            "micro_inertia": micropolar_length ** 2}


def command_generate(arguments) -> int:
    spacing = arguments.gap / arguments.gap_in_spacings
    smoothing_length = SUPPORT_OVER_SPACING * spacing
    inner_radius = arguments.inner_radius_in_gaps * arguments.gap
    outer_radius = inner_radius + arguments.gap
    eccentricity = arguments.eccentricity_in_spacings * spacing
    wall_thickness = WALL_LAYERS * spacing
    half_extent = outer_radius + wall_thickness + 2.0 * spacing
    count = int(np.ceil(half_extent / spacing)) + 2
    index = np.arange(-count, count + 1, dtype=np.float64)
    grid_x, grid_y = np.meshgrid(index + arguments.lattice_offset[0], index + arguments.lattice_offset[1],
                                 indexing="ij")
    angle = np.radians(arguments.lattice_angle)
    x = spacing * (np.cos(angle) * grid_x - np.sin(angle) * grid_y).ravel()
    y = spacing * (np.sin(angle) * grid_x + np.cos(angle) * grid_y).ravel()
    radius_outer = np.hypot(x, y)
    radius_inner = np.hypot(x - eccentricity, y)
    fluid = (radius_inner > inner_radius) & (radius_outer < outer_radius)
    inner_wall = (radius_inner <= inner_radius) & (radius_inner > inner_radius - wall_thickness)
    outer_wall = (radius_outer >= outer_radius) & (radius_outer < outer_radius + wall_thickness)
    points = np.column_stack([x, y])

    wall_speed = arguments.wall_speed
    rotation_rate = wall_speed / inner_radius
    far_viscosity = wall_speed * arguments.gap / arguments.reynolds          # nu_inf = U g / Re
    speed_of_sound = wall_speed / arguments.mach
    micropolar = arguments.coupling_ratio is not None
    if micropolar:
        micropolar_length = arguments.gap / (2.0 * arguments.gap_over_two_lengths)
        design = design_parameters(far_viscosity, arguments.coupling_ratio, micropolar_length)
    else:
        design = {"viscosity": far_viscosity, "viscosity_transfer": 0.0, "coupling": 0.0,
                  "viscosity_rotation": 0.0, "micro_inertia": 0.0}
    # the step: the Newtonian control of a micropolar run takes the micropolar run's limits (--step-from)
    limits = design
    if arguments.step_from_coupling_ratio is not None:
        limits = design_parameters(far_viscosity, arguments.step_from_coupling_ratio,
                                   arguments.gap / (2.0 * arguments.step_from_gap_over_two_lengths))
    dt_acoustic = arguments.cfl * smoothing_length / speed_of_sound
    dt_viscous = arguments.step_number * smoothing_length ** 2 / max(limits["viscosity"], design["viscosity"])
    dt_angular = (arguments.step_number_angular * smoothing_length ** 2
                  / (limits["viscosity_rotation"] / limits["micro_inertia"])
                  if limits["micro_inertia"] > 0.0 else float("inf"))
    timestep = min(dt_acoustic, dt_viscous, dt_angular)
    governing = {dt_acoustic: "acoustic", dt_viscous: "viscous", dt_angular: "angular diffusion"}[timestep]
    end_time = arguments.end_time_factor * arguments.gap ** 2 / far_viscosity
    steps = int(np.ceil(end_time / timestep / 1000.0)) * 1000

    out_dir = (_REPO_ROOT / arguments.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    _write_points(out_dir / "domain.obj", points[fluid], "annulus fluid")
    _write_points(out_dir / "wall_inner.obj", points[inner_wall], "inner cylinder (rotor) shell")
    _write_points(out_dir / "wall_outer.obj", points[outer_wall], "outer cylinder (stator) shell")
    with open(out_dir / "frame.obj", "w", encoding="utf-8", newline="\n") as handle:
        handle.write("# annulus frame bbox\n")
        for sign_x in (-1.0, 1.0):
            for sign_y in (-1.0, 1.0):
                for sign_z in (-1.0, 1.0):
                    handle.write(f"v {sign_x * half_extent:.9f} {sign_y * half_extent:.9f} "
                                 f"{sign_z * 0.5 * spacing:.9f}\n")
    rotor_micro_rotation = rotation_rate * arguments.rotor_micro_rotation_factor if micropolar else 0.0
    (out_dir / "materials.yaml").write_text(MATERIALS_TEMPLATE.format(
        density=1000.0, viscosity=float(design["viscosity"]), viscosity_transfer=float(design["viscosity_transfer"]),
        viscosity_rotation=float(design["viscosity_rotation"]), rotation_rate=float(rotation_rate),
        eccentricity=float(eccentricity), rotor_micro_rotation=float(rotor_micro_rotation)),
        encoding="utf-8", newline="\n")
    total = int(fluid.sum() + inner_wall.sum() + outer_wall.sum())
    if micropolar:
        parameters = (f"Micropolar: K = kappa / mu = {arguments.coupling_ratio:g}, m = g / (2 l) = "
                      f"{arguments.gap_over_two_lengths:g} (l = {micropolar_length / spacing:g} dx); nu = "
                      f"{design['viscosity']:.6e}, nu_t = {design['viscosity_transfer']:.6e}, c = "
                      f"{design['coupling']:.6e}, xi = {design['viscosity_rotation']:.6e}, Theta = "
                      f"{design['micro_inertia']:.6e}; rotor micro-rotation = {arguments.rotor_micro_rotation_factor:g} Omega.")
        micropolar_block = f"  micropolar:\n    enabled: true\n    micro_inertia: {design['micro_inertia']!r}\n"
    else:
        parameters = f"Newtonian: nu = nu_inf = {far_viscosity:.6e}."
        micropolar_block = ""
    meta = {
        "title": arguments.title or out_dir.name, "spacing": spacing, "smoothing_length": smoothing_length,
        "gap": arguments.gap, "inner_radius": inner_radius, "outer_radius": outer_radius,
        "eccentricity": eccentricity, "rotation_rate": rotation_rate, "wall_speed": wall_speed,
        "far_viscosity": far_viscosity, "reynolds": arguments.reynolds, "mach": arguments.mach,
        "speed_of_sound": speed_of_sound, "micropolar": micropolar, "coupling_ratio": arguments.coupling_ratio,
        "micropolar_length": micropolar_length if micropolar else None, **{f"design_{key}": value
                                                                             for key, value in design.items()},
        "rotor_micro_rotation": rotor_micro_rotation, "viscous_form": arguments.viscous_form,
        "epsilon_squared_factor": arguments.epsilon_squared_factor,
        "timestep": timestep, "dt_acoustic": dt_acoustic, "dt_viscous": dt_viscous, "dt_angular": dt_angular,
        "governing": governing, "step_number": arguments.step_number,
        "step_number_angular": arguments.step_number_angular, "end_time": end_time, "steps": steps,
        "fluid_count": int(fluid.sum()), "inner_count": int(inner_wall.sum()), "outer_count": int(outer_wall.sum()),
        "lattice_offset": list(arguments.lattice_offset), "lattice_angle": arguments.lattice_angle,
        "radii_in_spacings": {
            "fluid_at_inner_wall_min": float(radius_inner[fluid].min() / spacing),
            "fluid_at_outer_wall_max": float(radius_outer[fluid].max() / spacing),
            "inner_wall_min": float(radius_inner[inner_wall].min() / spacing),
            "inner_wall_max": float(radius_inner[inner_wall].max() / spacing),
            "outer_wall_min": float(radius_outer[outer_wall].min() / spacing),
            "outer_wall_max": float(radius_outer[outer_wall].max() / spacing)},
    }
    (out_dir / "case.yaml").write_text(CASE_TEMPLATE.format(
        title=meta["title"], inner_radius=inner_radius, inner_radius_dx=inner_radius / spacing,
        eccentricity=eccentricity, rotation_rate=rotation_rate, wall_speed=wall_speed, outer_radius=outer_radius,
        outer_radius_dx=outer_radius / spacing, spacing=spacing, smoothing_length=smoothing_length,
        offset_x=arguments.lattice_offset[0], offset_y=arguments.lattice_offset[1], angle=arguments.lattice_angle,
        fluid_count=meta["fluid_count"], inner_count=meta["inner_count"], outer_count=meta["outer_count"],
        wall_layers=WALL_LAYERS, parameters=parameters, dt_acoustic=dt_acoustic, dt_viscous=dt_viscous,
        dt_angular=dt_angular, cfl_nominal=arguments.cfl, step_number=arguments.step_number, timestep=timestep,
        governing=governing, cfl_effective=timestep * speed_of_sound / smoothing_length, end_time=end_time,
        steps=steps, particle_radius=0.5 * spacing, speed_of_sound=speed_of_sound,
        micropolar_block=micropolar_block, epsilon_squared_factor=arguments.epsilon_squared_factor,
        viscous_form=arguments.viscous_form, pool_size=int(1.25 * total) + 4096),
        encoding="utf-8", newline="\n")
    (out_dir / "couette.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    radii = meta["radii_in_spacings"]
    print(f"[couette] {out_dir.name}: fluid {meta['fluid_count']:,}, rotor {meta['inner_count']:,}, stator "
          f"{meta['outer_count']:,}; radii in dx: fluid from {radii['fluid_at_inner_wall_min']:.4f} to "
          f"{radii['fluid_at_outer_wall_max']:.4f}, rotor {radii['inner_wall_min']:.4f} to "
          f"{radii['inner_wall_max']:.4f}, stator {radii['outer_wall_min']:.4f} to {radii['outer_wall_max']:.4f}; "
          f"dt = {timestep:.4e} ({governing}), {steps:,} steps")
    return 0


def _sector_bins(positions, centre_x, inner_radius, outer_radius, spacing):
    """(sector index, radial bin index, radius, cos, sin) about the rotor axis; bins of one spacing from R1."""
    offset_x = positions[:, 0].astype(np.float64) - centre_x
    offset_y = positions[:, 1].astype(np.float64)
    radius = np.hypot(offset_x, offset_y)
    angle = np.arctan2(offset_y, offset_x)
    sector = np.floor((angle % (2.0 * np.pi)) / (2.0 * np.pi / SECTOR_COUNT)).astype(np.int64) % SECTOR_COUNT
    radial = np.floor((radius - inner_radius) / spacing).astype(np.int64)
    return sector, radial, radius, offset_x / radius, offset_y / radius


def command_run(arguments) -> int:
    from experiment.validation import micropolar_tests as tests
    solver = tests._import_solver(_REPO_ROOT)
    load_case, compute_chain_partition, SphSimulatorV7, VulkanContextV7, ChainOrchestratorV7 = solver
    from experiment.v7.utils.case_v7 import KIND_FLUID
    case_dir = (_REPO_ROOT / arguments.case).resolve()
    meta = json.loads((case_dir / "couette.json").read_text(encoding="utf-8"))
    case = load_case(case_dir / "case.yaml")
    device_map = [int(value) for value in arguments.device_map.split(",")]
    slab_count = len(device_map)
    weights = [float(value) for value in arguments.weights.split(",")] if arguments.weights else [1.0] * slab_count
    steps = arguments.steps if arguments.steps is not None else meta["steps"]
    cadence = case.numerics.defrag_cadence
    if arguments.sample_steps % cadence or steps % arguments.sample_steps:
        sys.exit(f"--sample-steps must be a multiple of {cadence} and divide the step count {steps}")
    timestep = float(case.physics.timestep)
    fluid_group = next(index for index, material in enumerate(case.materials) if material.kind == KIND_FLUID)
    micropolar = bool(case.physics.micropolar_enabled)
    bin_count = int(round((meta["outer_radius"] - meta["inner_radius"]) / meta["spacing"]))
    shape = (SECTOR_COUNT, bin_count)
    samples = {"step": [], "count": [], "radius": [], "velocity": [], "radial_velocity": [], "spin": [],
               "kinetic_energy": [], "density_min": [], "density_max": []}
    expected = int(case.initial.positions.shape[0])
    chain = compute_chain_partition(case, weights, pool_safety=arguments.pool_safety)
    out_dir = (_REPO_ROOT / arguments.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    contexts, sims = [], []
    started = time.perf_counter()
    failure = None
    try:
        for index in range(slab_count):
            contexts.append(VulkanContextV7.create(device_index=device_map[index], enable_validation=False,
                                                   application_name=f"couette_k{slab_count}_s{index}"))
            sims.append(SphSimulatorV7(contexts[-1], chain.slabs[index], sync_scheme="per-direction"))

        def sample(step: int) -> None:
            parts = [tests._read_own_particles(sim, ["density_pressure"] + (["angular_velocity"] if micropolar
                                                                              else [])) for sim in sims]
            rows = {name: np.concatenate([part[name] for part in parts]) for name in parts[0]}
            if rows["material"].shape[0] != expected:
                raise RuntimeError(f"step {step}: {rows['material'].shape[0]} particles alive, {expected} loaded")
            fluid = rows["material"] == fluid_group
            positions = rows["position_voxel_id"][fluid]
            velocity = rows["velocity_mass"][fluid, :2].astype(np.float64)
            if not np.isfinite(velocity).all():
                raise RuntimeError(f"step {step}: non-finite velocity")
            sector, radial, radius, cosine, sine = _sector_bins(positions, meta["eccentricity"],
                                                                meta["inner_radius"], meta["outer_radius"],
                                                                meta["spacing"])
            inside = (radial >= 0) & (radial < bin_count)
            flat = (sector * bin_count + radial)[inside]
            tangential = (-sine * velocity[:, 0] + cosine * velocity[:, 1])[inside]
            outward = (cosine * velocity[:, 0] + sine * velocity[:, 1])[inside]
            size = SECTOR_COUNT * bin_count
            samples["step"].append(step)
            samples["count"].append(np.bincount(flat, minlength=size).reshape(shape))
            samples["radius"].append(np.bincount(flat, radius[inside], size).reshape(shape))
            samples["velocity"].append(np.bincount(flat, tangential, size).reshape(shape))
            samples["radial_velocity"].append(np.bincount(flat, outward, size).reshape(shape))
            spin = (rows["angular_velocity"][fluid, 2].astype(np.float64)[inside] if micropolar
                    else np.zeros(int(inside.sum())))
            samples["spin"].append(np.bincount(flat, spin, size).reshape(shape))
            samples["kinetic_energy"].append(float(0.5 * (rows["velocity_mass"][fluid, 3].astype(np.float64)
                                                         * (velocity ** 2).sum(axis=1)).sum()))
            samples["density_min"].append(float(rows["density_pressure"][fluid, 0].min()))
            samples["density_max"].append(float(rows["density_pressure"][fluid, 0].max()))

        def on_defrag(frame: int, report: list) -> None:
            for index, entry in enumerate(report):
                bad = {key: value for key, value in entry.items()
                       if (key.startswith("overflow_") or key == "far_migration") and value}
                if bad:
                    raise RuntimeError(f"invariant violation at step {frame}, sim {index}: {bad}")
            if frame > 0 and frame % arguments.sample_steps == 0:
                sample(frame)

        with ChainOrchestratorV7(sims, defrag_cadence=cadence) as orchestrator:
            orchestrator.bootstrap_all()
            try:
                orchestrator.run_pipelined(steps, depth=arguments.depth, on_defrag=on_defrag)
                if not samples["step"] or samples["step"][-1] != steps:
                    sample(steps)
            except RuntimeError as error:
                failure = str(error)
            statuses = [sim.readback_global_status() for sim in sims]
    finally:
        for sim in sims:
            sim.destroy()
        for context in contexts:
            context.destroy()
    counters = {}
    for status in statuses:
        for name, value in status.items():
            if name.startswith("overflow_") or name in ("far_migration_count", "stamp_error_count"):
                counters[name] = counters.get(name, 0) + int(value)
    elapsed = time.perf_counter() - started
    np.savez(out_dir / "samples.npz", **{name: np.asarray(values) for name, values in samples.items()})
    run_meta = {"case": arguments.case, "couette": meta, "slabs": slab_count, "device_map": device_map,
                "weights": weights, "steps": steps, "sample_steps": arguments.sample_steps, "timestep": timestep,
                "particles": expected, "counters": counters, "elapsed_seconds": elapsed, "failure": failure,
                "steps_per_second": steps / elapsed, "cuts_x": tests._cut_positions(case, chain),
                "slab_particles": [int(slab.initial.positions.shape[0]) for slab in chain.slabs]}
    (out_dir / "run.json").write_text(json.dumps(run_meta, indent=1), encoding="utf-8")
    zero = all(value == 0 for value in counters.values())
    print(f"[couette] {out_dir.name}: {steps:,} steps (t = {steps * timestep:.4f}) in {elapsed:.0f} s, "
          f"{len(samples['step'])} samples, counters {'all zero' if zero else counters}"
          + (f"; FAILED: {failure}" if failure else ""))
    return 0 if zero and failure is None else 1


def command_step_limit(arguments) -> int:
    """Stage 3, section 2: the explicit step limits of the thesis configuration, measured as on v8-tgv for the
    Monaghan-Gingold form (short runs at increasing dt nu / h^2 until one fails), by bisection.

    The step dt and the acoustic CFL number stay fixed (the case's); the scanned number s = dt D / h^2 is raised
    through the diffusivity D itself: the viscosity nu (Newtonian annulus, either viscous form), or xi / Theta with
    the coupling switched off (c = 0: w obeys Theta dw/dt = xi lap w alone and is driven by the rotor's wall value).
    A probe fails when particles are lost, a counter is non-zero, a value is not finite, the fluid speed exceeds
    3 U, the density leaves rho_0 (1 +- 0.05) or, for the angular scan, |w| exceeds 10 Omega."""
    from experiment.validation import micropolar_tests as tests
    solver = tests._import_solver(_REPO_ROOT)
    from experiment.v7.utils.case_v7 import KIND_FLUID
    results = []

    def probe(kind: str, number: float) -> dict:
        case_dir = (_REPO_ROOT / (arguments.micropolar_case if kind == "angular" else arguments.case)).resolve()
        meta = json.loads((case_dir / "couette.json").read_text(encoding="utf-8"))
        case = solver[0](case_dir / "case.yaml")
        smoothing_length = float(case.physics.smoothing_length)
        timestep = float(case.physics.timestep)
        diffusivity = number * smoothing_length ** 2 / timestep
        fluid = next(material for material in case.materials if material.kind == KIND_FLUID)
        if kind == "angular":
            fluid.viscosity_transfer = -fluid.viscosity                       # c = 0
            fluid.viscosity_rotation = diffusivity * float(case.physics.micro_inertia)
        else:
            case.numerics.viscous_form = kind
            for material in case.materials:
                material.viscosity = diffusivity
        fields = ["density_pressure"] + (["angular_velocity"] if kind == "angular" else [])
        record = {"kind": kind, "number": number, "diffusivity": diffusivity, "timestep": timestep,
                  "steps": arguments.steps}
        try:
            rows, invariants = tests._run_chain(solver, case, 1, [arguments.device], [1.0], arguments.steps, fields,
                                                False)
        except Exception as error:                                           # a stalled or broken run is a failure
            record.update({"failed": True, "reason": f"{type(error).__name__}: {error}"[:200]})
            return record
        is_fluid = rows["material"] == next(index for index, material in enumerate(case.materials)
                                            if material.kind == KIND_FLUID)
        speed = np.sqrt((rows["velocity_mass"][is_fluid, :2].astype(np.float64) ** 2).sum(axis=1))
        density = rows["density_pressure"][is_fluid, 0].astype(np.float64)
        record.update({"alive": invariants["particles_alive"], "loaded": invariants["particles_loaded"],
                       "max_speed": float(np.nanmax(speed)) if speed.size else float("nan"),
                       "density_min": float(np.nanmin(density)), "density_max": float(np.nanmax(density))})
        reasons = []
        if invariants["particles_alive"] != invariants["particles_loaded"]:
            reasons.append("particles lost")
        if any(invariants["counters"].values()):
            reasons.append("counters")
        if not (np.isfinite(speed).all() and np.isfinite(density).all()):
            reasons.append("not finite")
        elif record["max_speed"] > 3.0 * meta["wall_speed"]:
            reasons.append("speed")
        elif record["density_min"] < 950.0 or record["density_max"] > 1050.0:
            reasons.append("density")
        if kind == "angular":
            spin = rows["angular_velocity"][is_fluid, 2].astype(np.float64)
            record["max_spin_over_rotation_rate"] = (float(np.nanmax(np.abs(spin))) / meta["rotation_rate"]
                                                     if np.isfinite(spin).any() else float("inf"))
            if not np.isfinite(spin).all() or record["max_spin_over_rotation_rate"] > 10.0:
                reasons.append("spin")
        record.update({"failed": bool(reasons), "reason": ", ".join(reasons)})
        return record

    summary = {}
    for kind in arguments.kinds:
        low, high = arguments.low, arguments.high
        for bound in (low, high):
            record = probe(kind, bound)
            results.append(record)
            print(f"[step-limit] {kind}: s = {bound:.5f} -> {'FAIL (' + record['reason'] + ')' if record['failed'] else 'stable'}",
                  flush=True)
        if results[-2]["failed"] or not results[-1]["failed"]:
            print(f"[step-limit] {kind}: the bracket [{low}, {high}] does not contain the threshold")
            summary[kind] = None
            continue
        while high / low - 1.0 > arguments.tolerance:
            middle = float(np.sqrt(low * high))
            record = probe(kind, middle)
            results.append(record)
            print(f"[step-limit] {kind}: s = {middle:.5f} -> {'FAIL (' + record['reason'] + ')' if record['failed'] else 'stable'}",
                  flush=True)
            if record["failed"]:
                high = middle
            else:
                low = middle
        summary[kind] = {"largest_stable": low, "smallest_failing": high}
        print(f"[step-limit] {kind}: threshold between {low:.5f} and {high:.5f} (dt D / h^2, {arguments.steps} steps); "
              f"/ 1.6 = {low / 1.6:.5f}")
    if arguments.json:
        pathlib.Path(arguments.json).parent.mkdir(parents=True, exist_ok=True)
        pathlib.Path(arguments.json).write_text(json.dumps({"summary": summary, "probes": results}, indent=1),
                                                encoding="utf-8")
    return 0


