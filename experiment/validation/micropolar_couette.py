    generate.add_argument("--out", required=True, help="case directory, relative to the repository root")
    generate.add_argument("--title", default=None)
    generate.add_argument("--gap", type=float, default=0.1, help="gap width g in metres")
    generate.add_argument("--gap-in-spacings", type=float, default=100.0)
    generate.add_argument("--inner-radius-in-gaps", type=float, default=4.0)
    generate.add_argument("--eccentricity-in-spacings", type=float, default=0.0)
    generate.add_argument("--lattice-offset", type=float, nargs=2, default=[0.0, 0.0], help="in spacings")
    generate.add_argument("--lattice-angle", type=float, default=0.0, help="degrees")
    generate.add_argument("--wall-speed", type=float, default=1.0)
    generate.add_argument("--reynolds", type=float, default=10.0, help="rho U g / mu_inf")
    generate.add_argument("--mach", type=float, default=0.02)
    generate.add_argument("--coupling-ratio", type=float, default=None, help="K = kappa / mu; absent = Newtonian")
    generate.add_argument("--gap-over-two-lengths", type=float, default=None, help="m = g / (2 l)")
    generate.add_argument("--rotor-micro-rotation-factor", type=float, default=1.0, help="w_wall / Omega on the rotor")
    generate.add_argument("--step-from-coupling-ratio", type=float, default=None,
                          help="take the step limits of the micropolar case with this K (the Newtonian control)")
    generate.add_argument("--step-from-gap-over-two-lengths", type=float, default=None)
    generate.add_argument("--cfl", type=float, default=0.15)
    generate.add_argument("--step-number", type=float, required=True, help="s in dt <= s h^2 / nu")
    generate.add_argument("--step-number-angular", type=float, required=True, help="s in dt <= s h^2 / (xi / Theta)")
    generate.add_argument("--end-time-factor", type=float, default=2.0, help="end time in g^2 / nu_inf")
    generate.add_argument("--viscous-form", default="laplacian", choices=("monaghan_gingold", "laplacian"))
    generate.add_argument("--epsilon-squared-factor", default="1.0e-6")
    generate.set_defaults(handler=command_generate)

    run = commands.add_parser("run")
    run.add_argument("--case", required=True, help="case directory")
    run.add_argument("--out", required=True)
    run.add_argument("--device-map", default="0")
    run.add_argument("--weights", default=None)
    run.add_argument("--steps", type=int, default=None, help="default: the case's end time")
    run.add_argument("--sample-steps", type=int, default=1000)
    run.add_argument("--depth", type=int, default=2)
    run.add_argument("--pool-safety", type=float, default=1.2)
    run.set_defaults(handler=command_run)

    pilot = commands.add_parser("pilot")
    pilot.add_argument("names", nargs="*", help="runs of the pilot table (default: all)")
    pilot.add_argument("--device", type=int, default=0, help="device of the one-slab and one-card runs")
    pilot.set_defaults(handler=command_pilot)

    analyse = commands.add_parser("analyse")
    analyse.add_argument("names", nargs="*", help="runs of the pilot table (default: every finished one)")
    analyse.add_argument("--json", default=None)
    analyse.set_defaults(handler=command_analyse)

    limit = commands.add_parser("step-limit")
    limit.add_argument("--case", default="cases/couette/step_probe", help="a Newtonian annulus case directory")
    limit.add_argument("--micropolar-case", default="cases/couette/step_probe_micropolar")
    limit.add_argument("--kinds", nargs="+", default=["laplacian", "monaghan_gingold", "angular"],
                       choices=("laplacian", "monaghan_gingold", "angular"))
    limit.add_argument("--low", type=float, default=0.012)
    limit.add_argument("--high", type=float, default=0.12)
    limit.add_argument("--tolerance", type=float, default=0.03, help="relative width of the final bracket")
    limit.add_argument("--steps", type=int, default=2000)
    limit.add_argument("--device", type=int, default=0)
    limit.add_argument("--json", default=None)
    limit.set_defaults(handler=command_step_limit)

    arguments = parser.parse_args()
    return arguments.handler(arguments)


