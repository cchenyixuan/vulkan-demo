"""
micropolar_couette.py - flow between a rotating inner cylinder and a fixed outer one (docs/micropolar_design.md,
Stage 3): the annulus case generator, the run driver and the host-side diagnostics against the exact solution of
micropolar_couette_reference.py.

  generate   Fluid on a Cartesian lattice (optionally shifted and rotated) between the inner cylinder (radius
             R1, centre offset by the eccentricity along x) and the outer one (radius R2, centred on the origin),
             wall shells on both sides, a material file and a case.yaml in the thesis configuration
             (numerics.viscous_form laplacian, epsilon_squared_factor 1e-6, wall_boundary adami). The inner wall
             is a material in rigid rotation (material key rigid_rotation); its micro-rotation is set separately.
             dt = min(CFL h / c0, s h^2 / nu, s h^2 / (xi / Theta)); the case stores it as an effective CFL number
             dt c0 / h (the solver's dt is CFL h / c0 and its shifting scale follows the same number), and the
             header says which limit governs.
  run        One case on a K-slab chain to its end time, sampling v_theta and w_z of the fluid in radial bins of
             one particle spacing and eight 45-degree sectors at every --sample-steps (defrag boundaries).
  analyse    Time averages, fits and the comparison with the reference solution for a list of runs.

Lengths in the generator are given in particle spacings dx.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import time

import numpy as np

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

SUPPORT_OVER_SPACING = 5              # h / dx of the 2-D cases
WALL_LAYERS = 11                      # wall shell thickness in particle spacings (as the cavity's frame: 2.2 h)
SECTOR_COUNT = 8

