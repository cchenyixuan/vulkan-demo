"""
micropolar_stage6_cavity.py - Stage 6, 2.3: the micropolar lid-driven cavity of the chapter.

Thesis configuration with the default walls (a cavity keeps the density diffusion towards its walls; no
numerics.delta_fluid_only), Ma = 0.01, K = 3, w = 0 on the four walls, Reynolds number 400 on mu_inf (1,000 on mu),
l = L / 20, Theta = l^2.

  mp_n500               the micropolar case at n = 500 (l = 25 dx), one slab
  mp_n250               the same at n = 250 (l = 12.5 dx)
  mp_n500_k2            the case of mp_n500 on two slabs (5090 + XTX)
  newtonian_re400_n500  Newtonian fluid of viscosity mu_inf (Reynolds number 400): far from walls the micropolar
                        fluid has this viscosity
  newtonian_re250_n500  Newtonian fluid of viscosity mu + kappa (Reynolds number 250): inside a wall layer it has
                        this one

  cases     Write the case directories (cases/stage6_cavity_<case>).
  run       One run with cavity_runner.py (v7, release switches, as the cavity runs of the thesis).
  analyse   Centre lines, extrema, levels and their drift; the micropolar run against the two Newtonian bounds,
            n = 250 against n = 500, two slabs against one.
  fields    The final state of one run with the curl of the velocity, as a file for the repository.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys

import numpy as np

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

TEMPLATE = "cases/viscous_cavity_n{n}_laplacian_eps1em6/case.yaml"
RUNS_DIRECTORY = "logs/micropolar/stage6_cavity"
FAR_VISCOSITY = 1.0 / 400.0            # nu_inf: Reynolds number 400 on mu_inf (U = 1 m/s, L = 1 m)
COUPLING_RATIO = 3.0
LENGTH = 1.0 / 20.0                    # l = L / 20
DENSITY, WALL_SPEED = 1000.0, 1.0
# run -> (case, resolution, micropolar, kinematic viscosity of the Newtonian fluid, slabs)
RUNS = {
    "mp_n500": ("mp_n500", 500, True, None, 1),
    "newtonian_re400_n500": ("newtonian_re400_n500", 500, False, FAR_VISCOSITY, 1),
    "newtonian_re250_n500": ("newtonian_re250_n500", 500, False, None, 1),       # nu = (mu + kappa) / rho, below
    "mp_n250": ("mp_n250", 250, True, None, 1),
    "mp_n500_k2": ("mp_n500", 500, True, None, 2),
}
MATERIALS = """# GENERATED by experiment/validation/micropolar_stage6_cavity.py with the case beside it.
schema_version: 1

cavity_fluid:
  kind: fluid
  rest_density: {density}
  viscosity: {viscosity!r}
{micropolar_lines}
stick_wall:
  kind: boundary
  rest_density: {density}
  viscosity: {viscosity!r}
  wall_angular_velocity: [0.0, 0.0, 0.0]

stick_lid:
  kind: boundary
  rest_density: {density}
  viscosity: {viscosity!r}
  initial_velocity: [1.0, 0.0, 0.0]
  wall_angular_velocity: [0.0, 0.0, 0.0]
"""


def design() -> dict:
    from experiment.validation.micropolar_couette import design_parameters
    return design_parameters(FAR_VISCOSITY, COUPLING_RATIO, LENGTH)


def case_viscosity(run: str) -> float:
    case, _resolution, micropolar, viscosity, _slabs = RUNS[run]
    if micropolar or case == "newtonian_re250_n500":
        return float(design()["viscosity"])                   # (mu + kappa) / rho
    return float(viscosity)


def make_case(run: str) -> pathlib.Path:
    case, resolution, micropolar, _viscosity, _slabs = RUNS[run]
    parameters = design()
    viscosity = case_viscosity(run)
    source = (_REPO_ROOT / TEMPLATE.format(n=resolution)).read_text(encoding="utf-8").replace("\r\n", "\n")
    header = (f"# VARIANT of cases/viscous_cavity_n{resolution}_laplacian_eps1em6 (the thesis configuration) for "
              f"docs/micropolar_design.md Section 15 (Stage 6, 2.3): ")
    if micropolar:
        header += (f"micropolar fluid, K = {COUPLING_RATIO:g}, nu_inf = {FAR_VISCOSITY!r} (Reynolds number 400 on "
                   f"mu_inf, 1,000 on mu), l = L / 20 = {LENGTH!r} m ({LENGTH * resolution:g} dx), Theta = l^2, "
                   "w = 0 on the four walls; everything else identical.\n")
        block = f"  micropolar:\n    enabled: true\n    micro_inertia: {parameters['micro_inertia']!r}\n"
        lines = (f"  viscosity_transfer: {parameters['viscosity_transfer']!r}\n"
                 f"  viscosity_rotation: {parameters['viscosity_rotation']!r}\n")
    else:
        header += (f"Newtonian fluid of kinematic viscosity {viscosity!r} (Reynolds number {1.0 / viscosity:g}), one "
                   "of the two bounds of the micropolar cavity; everything else identical.\n")
        block, lines = "", ""
    text = source.replace("schema_version: 2\n", "schema_version: 2\n\n" + header, 1)
    for old, new in (("  gravity: [0.0, 0.0, 0.0]\n", "  gravity: [0.0, 0.0, 0.0]\n" + block),
                     ("material_library: ../../materials/standard.yaml\n", "material_library: materials.yaml\n"),
                     ("material: stick_water}", "material: cavity_fluid}")):
        if text.count(old) != 1:
            raise RuntimeError(f"template line not found once: {old!r}")
        text = text.replace(old, new)
    case_dir = _REPO_ROOT / f"cases/stage6_cavity_{case}"
    case_dir.mkdir(parents=True, exist_ok=True)
    (case_dir / "case.yaml").write_text(text, encoding="utf-8", newline="\n")
    (case_dir / "materials.yaml").write_text(MATERIALS.format(density=DENSITY, viscosity=viscosity,
                                                              micropolar_lines=lines),
                                             encoding="utf-8", newline="\n")
    return case_dir


def command_cases(arguments) -> int:
    for run in RUNS:
        print(f"[stage6 cavity] {make_case(run)}")
    return 0


def command_run(arguments) -> int:
    from experiment.validation.cavity_campaign import environment
    run = arguments.run
    case, _resolution, _micropolar, _viscosity, slabs = RUNS[run]
    case_dir = make_case(run)
    devices = arguments.devices.split(",")
    if len(devices) != slabs:
        sys.exit(f"{run}: {slabs} slab(s), --devices names {len(devices)}")
    run_dir = _REPO_ROOT / RUNS_DIRECTORY / run
    if (run_dir / "done.json").exists():
        print(f"[stage6 cavity] {run}: done already", flush=True)
        return 0
    command = [sys.executable, "-m", "experiment.validation.cavity_runner", "--solver", "v7", "--case",
               str((case_dir / "case.yaml").relative_to(_REPO_ROOT)).replace("\\", "/"), "--run-dir", str(run_dir),
               "--slabs", str(slabs), "--device-map", arguments.devices, "--expect", "release", "--reynolds",
               repr(WALL_SPEED / case_viscosity(run)), "--t-end", str(arguments.t_end), "--t-max",
               str(arguments.t_max)]
    if arguments.max_steps:
        command += ["--max-steps", str(arguments.max_steps)]
    if run_dir.exists():
        command.append("--resume")
    run_dir.parent.mkdir(parents=True, exist_ok=True)
    with open(run_dir.parent / f"{run}.log", "a", encoding="utf-8") as log:
        code = subprocess.run(command, cwd=_REPO_ROOT, env=environment("release", "v7"), stdout=log,
                              stderr=subprocess.STDOUT).returncode
    print(f"[stage6 cavity] {run}: exit {code}", flush=True)
    if code == 0 and not arguments.max_steps:
        (run_dir / "done.json").write_text(json.dumps({"command": command}), encoding="utf-8")
    return code


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    cases = commands.add_parser("cases")
    cases.set_defaults(handler=command_cases)
    run = commands.add_parser("run")
    run.add_argument("run", choices=sorted(RUNS))
    run.add_argument("--devices", required=True, help="device index, or two for the run on two slabs: 0,1")
    run.add_argument("--t-end", type=float, default=40.0)
    run.add_argument("--t-max", type=float, default=80.0)
    run.add_argument("--max-steps", type=int, default=None, help="a short run (smoke test); leaves no done.json")
    run.set_defaults(handler=command_run)
    arguments = parser.parse_args()
    return arguments.handler(arguments)


if __name__ == "__main__":
    sys.exit(main())
