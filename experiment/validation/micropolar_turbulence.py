def coefficients() -> tuple:
    """The stream-function coefficients psi_hat on the modes -128..127 (fixed seed), Hermitian (a real field),
    E(k) proportional to k^4 exp(-2 (k / k0)^2) in unit shells, scaled to u' = 1. Returns (wavenumbers, psi_hat)."""
    modes = np.fft.fftfreq(2 * MODE_LIMIT, d=1.0 / (2 * MODE_LIMIT))
    kx, ky = np.meshgrid(modes, modes, indexing="ij")
    modulus = np.hypot(kx, ky)
    generator = np.random.default_rng(SEED)
    phases = np.exp(2j * np.pi * generator.random(kx.shape))
    # 2-D: E(k) = pi k |u_hat|^2 per shell (isotropic), |u_hat| = k |psi_hat|  ->  |psi_hat| ~ sqrt(E / (pi k^3))
    spectrum = modulus ** 4 * np.exp(-2.0 * (modulus / PEAK_WAVENUMBER) ** 2)
    with np.errstate(divide="ignore", invalid="ignore"):
        amplitude = np.where(modulus > 0, np.sqrt(spectrum / (np.pi * np.maximum(modulus, 1e-30) ** 3)), 0.0)
    psi_hat = amplitude * phases
    # Hermitian symmetry: the real part of the inverse transform of an arbitrary array is the field of
    # (a(k) + conj(a(-k))) / 2
    flipped = np.conj(np.roll(np.flip(psi_hat, axis=(0, 1)), 1, axis=(0, 1)))
    psi_hat = 0.5 * (psi_hat + flipped)
    psi_hat[MODE_LIMIT, :] = 0.0                 # the Nyquist rows and columns
    psi_hat[:, MODE_LIMIT] = 0.0
    return modes, psi_hat


def lattice_fields(side: int, shift: float) -> dict:
    """u, v, omega and p / rho of the field on the particle lattice x_i = (i + 0.5 + shift) dx (spectral)."""
    modes, psi_hat = coefficients()
    spacing = LENGTH / side
    full = np.fft.fftfreq(side, d=1.0 / side)
    kx, ky = np.meshgrid(full, full, indexing="ij")
    padded = np.zeros((side, side), dtype=np.complex128)
    index = np.mod(modes.astype(np.int64), side)
    padded[np.ix_(index, index)] = psi_hat
    offset = (0.5 + shift) * spacing
    padded *= np.exp(1j * (kx + ky) * offset)
    # with the box 2 pi the integer modes are the wavenumbers; the inverse transform's 1 / N^2 is compensated
    scale = side * side

    def real(spectral):
        return np.real(np.fft.ifft2(spectral)) * scale
    u = real(1j * ky * padded)                 # u = d psi / dy
    v = real(-1j * kx * padded)                # v = -d psi / dx
    norm = math.sqrt(0.5 * float(np.mean(u ** 2 + v ** 2)))
    u, v = u / norm, v / norm
    padded = padded / norm
    vorticity = real(-(kx ** 2 + ky ** 2) * padded) * -1.0     # omega = dv/dx - du/dy = -lap psi
    # pressure: lap p = -d_i d_j (u_i u_j) (rho = 1 here), zero mean
    u_hat, v_hat = (np.fft.fft2(field) for field in (u * u, u * v))
    w_hat = np.fft.fft2(v * v)
    source = -(-(kx ** 2) * u_hat - 2.0 * kx * ky * v_hat - (ky ** 2) * w_hat)
    with np.errstate(divide="ignore", invalid="ignore"):
        pressure_hat = np.where(kx ** 2 + ky ** 2 > 0, -source / (kx ** 2 + ky ** 2), 0.0)
    pressure = np.real(np.fft.ifft2(pressure_hat))
    return {"u": u, "v": v, "vorticity": vorticity, "pressure": pressure, "norm": norm}


def write_geometry(directory: pathlib.Path, side: int, shift: float) -> None:
    spacing = LENGTH / side
    coordinate = spacing * (np.arange(side) + 0.5 + shift)
    coordinate = np.where(coordinate >= LENGTH, coordinate - LENGTH, coordinate)
    x, y = np.meshgrid(coordinate, coordinate, indexing="ij")
    directory.mkdir(parents=True, exist_ok=True)
    with open(directory / "domain.obj", "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"# {side * side} particles\n")
        np.savetxt(handle, np.column_stack([x.ravel(), y.ravel(), np.zeros(side * side)]), fmt="v %.12f %.12f %.1f")
    depth = 0.5 * spacing
    corners = [(0.0, 0.0, -depth), (0.0, LENGTH, -depth), (LENGTH, 0.0, -depth), (LENGTH, LENGTH, -depth),
               (0.0, 0.0, depth), (0.0, LENGTH, depth), (LENGTH, 0.0, depth), (LENGTH, LENGTH, depth)]
    faces = ["f 1 2 4", "f 1 4 3", "f 5 7 8", "f 5 8 6", "f 1 5 6", "f 1 6 2", "f 3 4 8", "f 3 8 7", "f 1 3 7",
             "f 1 7 5", "f 2 6 8", "f 2 8 4"]
    (directory / "frame.obj").write_text("# periodic box\n" + "".join(f"v {a:.12f} {b:.12f} {c:.12f}\n"
                                                                      for a, b, c in corners)
                                         + "\n".join(faces) + "\n", encoding="utf-8")


def design(run: str) -> dict:
    from experiment.validation.micropolar_couette import design_parameters
    if not RUNS[run]["micropolar"]:
        return {"viscosity": FAR_VISCOSITY, "viscosity_transfer": -FAR_VISCOSITY, "coupling": 0.0,
                "viscosity_rotation": 0.0, "micro_inertia": MICROPOLAR_LENGTH ** 2, "length": None}
    parameters = design_parameters(FAR_VISCOSITY, COUPLING_RATIO, MICROPOLAR_LENGTH)
    parameters["micro_inertia"] *= RUNS[run].get("theta_factor", 1.0)
    return {**parameters, "length": MICROPOLAR_LENGTH}


def peak_speed() -> float:
    fields = lattice_fields(2050, 0.0)
    return float(np.sqrt(fields["u"] ** 2 + fields["v"] ** 2).max())


def make_case(run: str, speed: float) -> pathlib.Path:
    entry = RUNS[run]
    side, shift = entry["side"], entry["shift"]
    shift_label = "_shifted" if shift else ""
    geometry = _REPO_ROOT / f"cases/periodic/geometry_two_pi_n{side}{shift_label}"
    if not (geometry / "domain.obj").exists():
        write_geometry(geometry, side, shift)
    spacing = LENGTH / side
    support = SUPPORT_OVER_SPACING * spacing
    parameters = design(run)
    speed_of_sound = speed / MACH
    designs = [design(name) for name in RUNS]
    dt_acoustic = 0.15 * support / speed_of_sound
    dt_viscous = STEP_NUMBER * support ** 2 / max(item["viscosity"] for item in designs)
    rates = [item["viscosity_rotation"] / item["micro_inertia"] for item in designs if item["viscosity_rotation"]]
    dt_angular = STEP_NUMBER_ANGULAR * support ** 2 / max(rates)
    timestep = min(dt_acoustic, dt_viscous, dt_angular)
    governing = {dt_acoustic: "acoustic", dt_viscous: "viscous", dt_angular: "angular diffusion"}[timestep]
    steps = int(math.ceil(END_TIME / timestep / SAMPLE_STEPS - 1e-9)) * SAMPLE_STEPS
    if entry["micropolar"]:
        description = (f"Micropolar: K = {COUPLING_RATIO:g}, l = 1 / 7 = {MICROPOLAR_LENGTH:.6f} ({MICROPOLAR_LENGTH / spacing:.1f} "
                       f"dx), Theta = {entry.get('theta_factor', 1.0):g} l^2; nu = {parameters['viscosity']:.6g}, nu_t = {parameters['viscosity_transfer']:.6g}, "
                       f"c = {parameters['coupling']:.6g}, xi = {parameters['viscosity_rotation']:.6g}; nu_inf = "
                       f"{FAR_VISCOSITY:g}.")
    else:
        description = (f"Newtonian: nu_inf = {FAR_VISCOSITY:g} on the micropolar path (nu_t = -nu, xi = 0, passive w)"
                       + ("; particle lattice shifted by half a spacing in x and y" if shift else "") + ".")
    case_dir = _REPO_ROOT / f"cases/periodic/{run}"
    case_dir.mkdir(parents=True, exist_ok=True)
    count = side * side
    (case_dir / "case.yaml").write_text(CASE_TEMPLATE.format(
        title=run, side=side, count=count, spacing=spacing, smoothing_length=support,
        voxels=side // SUPPORT_OVER_SPACING, description=description, speed_of_sound=speed_of_sound, mach=MACH,
        peak_speed=speed, timestep=timestep, governing=governing, end_time=END_TIME, steps=steps,
        particle_radius=0.5 * spacing, cfl=timestep * speed_of_sound / support,
        micro_inertia=float(parameters["micro_inertia"]), pool_size=int(math.ceil(1.15 * count / 128.0)) * 128,
        shift_label=shift_label), encoding="utf-8", newline="\n")
    (case_dir / "materials.yaml").write_text(MATERIALS_TEMPLATE.format(
        viscosity=float(parameters["viscosity"]), viscosity_transfer=float(parameters["viscosity_transfer"]),
        viscosity_rotation=float(parameters["viscosity_rotation"])), encoding="utf-8", newline="\n")
    (case_dir / "turbulence.json").write_text(json.dumps({
        "run": run, **entry, "spacing": spacing, "smoothing_length": support, "speed_of_sound": speed_of_sound,
        "peak_initial_speed": speed, "timestep": timestep, "governing": governing, "steps": steps,
        "dt_acoustic": dt_acoustic, "dt_viscous": dt_viscous, "dt_angular": dt_angular, "design": parameters,
        "far_viscosity": FAR_VISCOSITY, "peak_wavenumber": PEAK_WAVENUMBER, "seed": SEED,
        "reynolds": 1.0 / (PEAK_WAVENUMBER * FAR_VISCOSITY), "reynolds_box": LENGTH / FAR_VISCOSITY,
        "reynolds_on_mu": (1.0 + COUPLING_RATIO / 2.0) / (PEAK_WAVENUMBER * FAR_VISCOSITY)}, indent=1),
        encoding="utf-8")
    return case_dir


class SpectralGrid:
    """Periodic quadratic B-spline deposit on GRID x GRID nodes of [0, 2 pi), Shepard-normalised; spectra in unit
    shells with the spline window divided out (|k| <= GRID / 4)."""

    def __init__(self):
        self.count = GRID
        self.spacing = LENGTH / GRID
        modes = np.fft.fftfreq(GRID, d=1.0 / GRID)
        self.kx, self.ky = np.meshgrid(modes, modes, indexing="ij")
        self.modulus = np.hypot(self.kx, self.ky)
        self.shell = np.rint(self.modulus).astype(np.int64)
        self.shells = GRID // 4
        argument_x, argument_y = 0.5 * self.kx * self.spacing, 0.5 * self.ky * self.spacing
        window = (np.sinc(argument_x / np.pi) * np.sinc(argument_y / np.pi)) ** 3
        self.window = np.where(self.modulus <= self.shells, window, 1.0)

    def deposit(self, position: np.ndarray, values: list) -> list:
        coordinate = position / self.spacing - 0.5
        nearest = np.rint(coordinate).astype(np.int64)
        offset = coordinate - nearest
        weights = [0.5 * (0.5 - offset) ** 2, 0.75 - offset ** 2, 0.5 * (0.5 + offset) ** 2]
        size = self.count * self.count
        volume = np.zeros(size)
        sums = [np.zeros(size) for _ in values]
        for step_x in range(3):
            column = np.mod(nearest[:, 0] + step_x - 1, self.count)
            for step_y in range(3):
                row = np.mod(nearest[:, 1] + step_y - 1, self.count)
                flat = column * self.count + row
                weight = weights[step_x][:, 0] * weights[step_y][:, 1]
                volume += np.bincount(flat, weight, size)
                for total, field in zip(sums, values):
                    total += np.bincount(flat, weight * field, size)
        volume = volume.reshape(self.count, self.count)
        safe = np.where(volume > 0, volume, 1.0)
        return [total.reshape(self.count, self.count) / safe for total in sums]

    def spectrum(self, u: np.ndarray, v: np.ndarray) -> dict:
        u_hat = np.fft.fft2(u) / u.size / self.window
        v_hat = np.fft.fft2(v) / v.size / self.window
        density = 0.5 * (np.abs(u_hat) ** 2 + np.abs(v_hat) ** 2)
        inside = self.shell <= self.shells
        energy = np.bincount(self.shell[inside], density[inside], self.shells + 1)
        vorticity_hat = 1j * self.kx * v_hat - 1j * self.ky * u_hat
        return {"energy_spectrum": energy, "vorticity_hat": vorticity_hat,
                "enstrophy": float(np.sum((np.arange(self.shells + 1) ** 2) * energy))}


def command_cases(arguments) -> int:
    speed = peak_speed()
    for run in arguments.runs or RUNS:
        print(f"[turbulence] {make_case(run, speed).relative_to(_REPO_ROOT)}", flush=True)
    return 0


def command_run(arguments) -> int:
    from experiment.validation import micropolar_tests as tests
    from experiment.validation.micropolar_couette import solver_revision
    from experiment.validation.micropolar_rotor3d import read_own_particles
    solver = tests._import_solver(_REPO_ROOT)
    load_case, compute_chain_partition, SphSimulatorV7, VulkanContextV7, ChainOrchestratorV7 = solver
    from experiment.v7.utils.case_v7 import KIND_FLUID
    run = arguments.run
    entry = RUNS[run]
    case_dir = _REPO_ROOT / f"cases/periodic/{run}"
    meta = json.loads((case_dir / "turbulence.json").read_text(encoding="utf-8"))
    case = load_case(case_dir / "case.yaml")
    timestep = float(case.physics.timestep)
    steps = meta["steps"] if arguments.steps is None else arguments.steps
    side, shift = entry["side"], entry["shift"]
    fields = lattice_fields(side, shift)
    spacing = LENGTH / side
    # the particles of the loader in lattice order: index from position
    position = case.initial.positions[:, :2].astype(np.float64)
    index = np.mod(np.rint(position / spacing - 0.5 - shift).astype(np.int64), side)
    flat = index[:, 0] * side + index[:, 1]
    velocities = case.initial.velocities.copy()
    velocities[:, 0] = fields["u"].ravel()[flat].astype(np.float32)
    velocities[:, 1] = fields["v"].ravel()[flat].astype(np.float32)
    case.initial.velocities = velocities
    spin = np.zeros((position.shape[0], 3), dtype=np.float32)
    spin[:, 2] = (0.5 * fields["vorticity"].ravel()[flat]).astype(np.float32)
    case.initial.angular_velocities = spin
    fluid_group = next(i for i, material in enumerate(case.materials) if material.kind == KIND_FLUID)
    material = case.materials[fluid_group]
    rest, constant, power = float(material.rest_density), float(material.eos_constant), float(case.physics.power_parameter)
    kinematic_pressure = fields["pressure"].ravel()
    initial_density = rest * np.power(1.0 + rest * kinematic_pressure / constant, 1.0 / power)
    initial_pressure = (np.float32(constant) * (np.power(initial_density.astype(np.float32) / np.float32(rest),
                                                         np.float32(power)) - np.float32(1.0))).astype(np.float32)
    grid = SpectralGrid()
    chain = compute_chain_partition(case, [1.0], pool_safety=arguments.pool_safety)
    out_dir = (_REPO_ROOT / RUNS_DIRECTORY / (run + (f"_{arguments.label}" if arguments.label else ""))).resolve()
    (out_dir / "fields").mkdir(parents=True, exist_ok=True)
    samples = {name: [] for name in ("step", "time", "energy", "energy_grid", "enstrophy", "energy_spectrum",
                                     "max_speed", "density_mean", "outside_box")}
    # the sample nearest each snapshot time (the first runs rounded to 1000 steps, which only t = 0.5 and 1 met)
    snapshot_steps = {SAMPLE_STEPS * int(round(value / timestep / SAMPLE_STEPS)) for value in SNAPSHOT_TIMES if value > 0}
    contexts, sims, statuses = [], [], []
    started = time.perf_counter()
    failure, bootstrap_seconds = None, None

    def record_sample(step: int, point: np.ndarray, velocity: np.ndarray, density_mean: float) -> None:
        u, v = grid.deposit(point, [velocity[:, 0], velocity[:, 1]])
        spectral = grid.spectrum(u, v)
        samples["step"].append(step)
        samples["time"].append(step * timestep)
        samples["energy"].append(float(0.5 * np.mean((velocity ** 2).sum(axis=1))))
        samples["energy_grid"].append(float(spectral["energy_spectrum"].sum()))
        samples["enstrophy"].append(spectral["enstrophy"])
        samples["energy_spectrum"].append(spectral["energy_spectrum"])
        samples["max_speed"].append(float(np.sqrt((velocity ** 2).sum(axis=1).max())))
        samples["density_mean"].append(density_mean)
        samples["outside_box"].append(int(((point < 0) | (point >= LENGTH)).any(axis=1).sum()))
        if step == 0 or step in snapshot_steps:
            vorticity = np.real(np.fft.ifft2(spectral["vorticity_hat"] * grid.window)) * GRID * GRID
            np.savez_compressed(out_dir / "fields" / f"vorticity_{step:08d}.npz", vorticity=vorticity.astype(np.float16),
                                time=step * timestep, step=step)

    # t = 0 from the initial field on the particles
    record_sample(0, position, np.column_stack([fields["u"].ravel()[flat], fields["v"].ravel()[flat]]), rest)
    try:
        contexts.append(VulkanContextV7.create(device_index=int(arguments.device), enable_validation=False,
                                               application_name="turbulence"))
        sim = SphSimulatorV7(contexts[-1], chain.slabs[0], sync_scheme="per-direction")
        sims.append(sim)
        original = sim._build_initial_data
        slab_initial = chain.slabs[0].initial

        def build() -> dict:
            data = original()
            pool_capacity = sim.case.capacities.total_pool_capacity()
            own_first = sim.own_first_pid()
            density_pressure = np.frombuffer(data["density_pressure"], np.float32).reshape(pool_capacity, 2).copy()
            points = slab_initial.positions[:, :2].astype(np.float64)
            slab_index = np.mod(np.rint(points / spacing - 0.5 - shift).astype(np.int64), side)
            slab_flat = slab_index[:, 0] * side + slab_index[:, 1]
            rows = np.arange(points.shape[0])
            density_pressure[own_first + rows, 0] = (initial_density[slab_flat] - sim.stored_density_offset()).astype(np.float32)
            density_pressure[own_first + rows, 1] = initial_pressure[slab_flat]
            data["density_pressure"] = density_pressure.tobytes()
            return data
        sim._build_initial_data = build

        def sample(step: int) -> None:
            rows = read_own_particles(sim, ["density_pressure", "acceleration"])
            fluid = rows["material"] == fluid_group
            point = rows["position_voxel_id"][fluid, :2].astype(np.float64)
            velocity = (rows["velocity_mass"][fluid, :2].astype(np.float64)
                        + 0.5 * timestep * rows["acceleration"][fluid, :2].astype(np.float64))
            if not np.isfinite(velocity).all():
                raise RuntimeError(f"step {step}: non-finite velocity")
            # the readback returns rho (the first runs added rho0 once more here: see load_run)
            density = rows["density_pressure"][fluid, 0].astype(np.float64)
            record_sample(step, point, velocity, float(density.mean()))
            if len(samples["step"]) % 10 == 0:
                # what a run that is stopped early leaves behind, and the resolution check during a run
                np.savez_compressed(out_dir / "samples_partial.npz",
                                    **{name: np.asarray(values) for name, values in samples.items()})
            (out_dir / "heartbeat.json").write_text(json.dumps({"step": step, "steps": steps, "time": step * timestep,
                                                                "elapsed_seconds": time.perf_counter() - started}),
                                                    encoding="utf-8")

        def on_defrag(frame: int, report: list) -> None:
            for item in report:
                bad = {key: value for key, value in item.items()
                       if (key.startswith("overflow_") or key == "far_migration") and value}
                if bad:
                    raise RuntimeError(f"invariant violation at step {frame}: {bad}")
            if frame > 0 and frame % SAMPLE_STEPS == 0:
                sample(frame)

        with ChainOrchestratorV7(sims, defrag_cadence=case.numerics.defrag_cadence) as orchestrator:
            orchestrator.bootstrap_all()
            bootstrap_seconds = time.perf_counter() - started
            try:
                orchestrator.run_pipelined(steps, depth=2, on_defrag=on_defrag)
                if samples["step"][-1] != steps:
                    sample(steps)
            except RuntimeError as error:
                failure = str(error)
            statuses = [sim.readback_global_status() for sim in sims]
    finally:
        for sim in sims:
            sim.destroy()
        for context in contexts:
            context.destroy()
    counters = {}
    for status in statuses:
        for name, value in status.items():
            if name.startswith("overflow_") or name in ("far_migration_count", "stamp_error_count"):
                counters[name] = counters.get(name, 0) + int(value)
    elapsed = time.perf_counter() - started
    np.savez_compressed(out_dir / "samples.npz", **{name: np.asarray(values) for name, values in samples.items()})
    record = {"run": run, "label": arguments.label, "case": f"cases/periodic/{run}", "turbulence": meta, "revision": solver_revision(),
              "device": int(arguments.device), "steps": steps, "timestep": timestep,
              "particles": int(case.initial.positions.shape[0]), "counters": counters, "elapsed_seconds": elapsed,
              "bootstrap_seconds": bootstrap_seconds, "failure": failure,
              "steps_per_second": steps / max(elapsed - (bootstrap_seconds or 0.0), 1e-9)}
    (out_dir / "run.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
    zero = all(value == 0 for value in counters.values())
    print(f"[turbulence] {run}: {steps:,} steps (t = {steps * timestep:.4f}) in {elapsed:.0f} s "
          f"({record['steps_per_second']:.1f} steps/s), counters {'all zero' if zero else counters}"
          + (f"; FAILED: {failure}" if failure else ""), flush=True)
    return 0 if zero and failure is None else 1


def linear_rates(wavenumbers: np.ndarray) -> dict:
    """Decay rates of a single Fourier mode of modulus q (the velocity amplitude): Newtonian nu_inf q^2; micropolar
    quasi-steady (j -> 0) mu_eff(q) q^2 / rho; micropolar with j = l^2, the slow eigenvalue of
    [[-nu q^2, c q], [c q / Theta, -(xi q^2 + 2 c) / Theta]] (the Taylor-Green system with 2 k^2 = q^2)."""
    parameters = design("turbulence_micropolar_n2050")
    nu, c, xi, theta = (parameters[key] for key in ("viscosity", "coupling", "viscosity_rotation", "micro_inertia"))
    shear = nu - c
    newtonian = FAR_VISCOSITY * wavenumbers ** 2
    s = (wavenumbers * MICROPOLAR_LENGTH) ** 2 * (2.0 * shear + c) / (2.0 * (shear + c))
    quasi = (shear + c / 2.0 + (c / 2.0) * s / (1.0 + s)) * wavenumbers ** 2
    exact = []
    for q in wavenumbers:
        matrix = np.array([[-nu * q * q, c * q], [c * q / theta, -(xi * q * q + 2.0 * c) / theta]])
        exact.append(float(-np.max(np.linalg.eigvals(matrix).real)))
    return {"newtonian": newtonian, "quasi_steady": quasi, "inertial": np.asarray(exact)}


def load_run(run: str):
    directory = _REPO_ROOT / RUNS_DIRECTORY / run
    if not (directory / "run.json").exists():
        return None
    record = json.loads((directory / "run.json").read_text(encoding="utf-8"))
    with np.load(directory / "samples.npz") as archive:
        samples = {name: np.array(archive[name]) for name in archive.files}
    # the run tool added the offset of the delta density storage (rho0, V7_DELTA_DENSITY=1) to a readback that
    # already returns rho: the diagnostic mean density of the samples after t = 0 carries rho0 twice (the solver's
    # state does not; the t = 0 sample is from the host)
    rest = 1000.0
    later = samples["density_mean"][1:]
    if later.size and np.all(later > 1.5 * rest):
        samples["density_mean"] = np.concatenate([samples["density_mean"][:1], later - rest])
    return {"record": record, "samples": samples}


def command_analyse(arguments) -> int:
    lines, result = [], {}

    def say(text: str = "") -> None:
        lines.append(text)
        print(text, flush=True)

    # the repeats (5090, after the first runs; they also carry the vorticity at t = 2, 3, 4): floors of the same
    # card (micropolar) and of the other card (the Newtonian first run was on the XTX)
    repeats = {f"{name}_repeat": name for name in ("turbulence_micropolar_n2050", "turbulence_newtonian_n2050")}
    runs = {name: load_run(name) for name in list(RUNS) + list(repeats)}
    runs = {name: value for name, value in runs.items() if value is not None}
    base = runs.get("turbulence_newtonian_n2050")
    if base is None:
        print("no Newtonian 2050 run yet")
        return 0
    say("Stage 8b: decaying 2-D turbulence (box 2 pi, k0 = 10, u' = 1, nu_inf = 1e-3: Re = u' / (k0 nu_inf) = 100, "
        "u' L / nu_inf = 6283; on mu: 250, 15708)")
    say(f"{'run':<38}{'particles':>11}{'steps':>9}{'dt':>11}{'steps/s':>9}{'wall':>8}  counters")
    for name, item in runs.items():
        record = item["record"]
        say(f"{name:<38}{record['particles']:>11,}{record['steps']:>9,}{record['timestep']:>11.3e}"
            f"{record['steps_per_second']:>9.1f}{record['elapsed_seconds'] / 60.0:>7.0f}m  "
            f"{'zero' if not any(record['counters'].values()) else record['counters']}")
        result.setdefault("runs", {})[name] = {key: record[key] for key in ("particles", "steps", "timestep",
                                                                           "steps_per_second", "elapsed_seconds",
                                                                           "counters", "failure")}
        result["runs"][name]["revision"] = record["revision"]
    times = base["samples"]["time"]
    shells = np.arange(base["samples"]["energy_spectrum"].shape[1])
    rates = linear_rates(shells.astype(np.float64))
    report_times = [time for time in SNAPSHOT_TIMES if time > 0]

    def at(item, time):
        index = int(np.argmin(np.abs(item["samples"]["time"] - time)))
        return index, item["samples"]["time"][index]
    series = {}
    for name, item in runs.items():
        series[name] = {key: item["samples"][key].tolist() for key in ("time", "energy", "energy_grid", "enstrophy",
                                                                      "max_speed", "density_mean")}
    result["series"] = series
    spectra = {}
    for time in report_times:
        index, actual = at(base, time)
        entry = {"time": float(actual), "newtonian": base["samples"]["energy_spectrum"][index].tolist()}
        for name in ("turbulence_micropolar_n2050", "turbulence_newtonian_n2050_shifted", "turbulence_newtonian_n1025",
                     "turbulence_micropolar_j001_n2050", *repeats):
            if name in runs:
                other_index, _other_time = at(runs[name], time)
                entry[name] = runs[name]["samples"]["energy_spectrum"][other_index].tolist()
        # the linear estimates of the micropolar over Newtonian energy ratio after the time t (E ~ amplitude^2)
        entry["linear_quasi_steady"] = np.exp(-2.0 * (rates["quasi_steady"] - rates["newtonian"]) * actual).tolist()
        entry["linear_inertial"] = np.exp(-2.0 * (rates["inertial"] - rates["newtonian"]) * actual).tolist()
        spectra[f"{time:g}"] = entry
    result["spectra"] = spectra
    result["shells"] = shells.tolist()
    say()
    say("micropolar over Newtonian: E, Z; noise floor from the shifted lattice")
    for time in report_times:
        index, actual = at(base, time)
        cells = []
        for name in ("turbulence_micropolar_n2050", "turbulence_newtonian_n2050_shifted", "turbulence_newtonian_n1025",
                     "turbulence_micropolar_j001_n2050"):
            if name not in runs:
                continue
            other_index, _ = at(runs[name], time)
            other = runs[name]["samples"]
            cells.append(f"{name.split('turbulence_')[1]}: E {other['energy'][other_index] / base['samples']['energy'][index] - 1.0:+.4f}, "
                         f"Z {other['enstrophy'][other_index] / base['samples']['enstrophy'][index] - 1.0:+.4f}")
        for name, original in repeats.items():
            if name in runs and original in runs:
                first_index, _ = at(runs[original], time)
                other_index, _ = at(runs[name], time)
                first, other = runs[original]["samples"], runs[name]["samples"]
                cells.append(f"{name.split('turbulence_')[1]} / first run: E "
                             f"{other['energy'][other_index] / first['energy'][first_index] - 1.0:+.4f}, Z "
                             f"{other['enstrophy'][other_index] / first['enstrophy'][first_index] - 1.0:+.4f}")
        say(f"  t = {actual:.3f}: Newtonian E {base['samples']['energy'][index]:.5f}, Z {base['samples']['enstrophy'][index]:.3f}; "
            + "; ".join(cells))
    # the spectrum ratio by band of wavenumbers
    say()
    say("spectrum ratio micropolar / Newtonian (mean over shells of each band), the shifted lattice's |ratio - 1| "
        "(floor), the 1025^2 run's ratio (resolution), the linear estimates (quasi-steady, with j = l^2)")
    bands = ((3, 7), (7, 15), (15, 30), (30, 60), (60, 120), (120, 200))
    table = {}
    for time in report_times:
        entry = spectra[f"{time:g}"]
        newtonian = np.asarray(entry["newtonian"])
        rows = []
        for low, high in bands:
            chosen = (shells >= low) & (shells < high) & (newtonian > 0)
            row = {"band": [low, high]}
            for name, label in (("turbulence_micropolar_n2050", "ratio"), ("turbulence_newtonian_n2050_shifted", "floor"),
                                ("turbulence_newtonian_n1025", "resolution"),
                                ("turbulence_micropolar_j001_n2050", "ratio_j001")):
                if name in entry:
                    ratio = np.asarray(entry[name])[chosen] / newtonian[chosen]
                    row[label] = float(np.mean(np.abs(ratio - 1.0))) if label == "floor" else float(np.mean(ratio))
            for name, original, label in (("turbulence_micropolar_n2050_repeat", "turbulence_micropolar_n2050",
                                           "repeat_floor"),
                                          ("turbulence_newtonian_n2050_repeat", "newtonian", "card_floor")):
                if name in entry and (original in entry):
                    reference = np.asarray(entry[original])[chosen]
                    row[label] = float(np.mean(np.abs(np.asarray(entry[name])[chosen] / reference - 1.0)))
            row["linear_quasi_steady"] = float(np.mean(np.asarray(entry["linear_quasi_steady"])[chosen]))
            row["linear_inertial"] = float(np.mean(np.asarray(entry["linear_inertial"])[chosen]))
            rows.append(row)
        table[f"{time:g}"] = rows
        say(f"  t = {entry['time']:.3f}: " + "; ".join(
            f"k {row['band'][0]}-{row['band'][1]}: " + ", ".join(f"{key} {row[key]:.3f}" for key in
                                                                 ("ratio", "ratio_j001", "floor", "repeat_floor", "card_floor",
                                                                  "resolution", "linear_quasi_steady",
                                                                  "linear_inertial") if key in row) for row in rows))
    result["bands"] = table
    out_dir = _REPO_ROOT / DATA_DIRECTORY
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "turbulence.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (out_dir / "turbulence.json").write_text(json.dumps(result, indent=1, default=float), encoding="utf-8")
    # the vorticity fields of the two repeats (the first runs wrote t = 0, 0.5, 1 only) at the snapshot times, at
    # half resolution, for the pack (float16)
    fields_dir = out_dir / "fields"
    fields_dir.mkdir(exist_ok=True)
    for name in repeats:
        for path in sorted((_REPO_ROOT / RUNS_DIRECTORY / name / "fields").glob("vorticity_*.npz")):
            with np.load(path) as archive:
                vorticity = np.array(archive["vorticity"], dtype=np.float32)
                half = vorticity.shape[0] // 2
                vorticity = vorticity.reshape(half, 2, half, 2).mean(axis=(1, 3))
                np.savez_compressed(fields_dir / f"{name}_t{float(archive['time']):.3f}.npz",
                                    vorticity=vorticity.astype(np.float16), time=float(archive["time"]))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    cases = commands.add_parser("cases")
    cases.add_argument("runs", nargs="*")
    run = commands.add_parser("run")
    run.add_argument("run", choices=sorted(RUNS))
    run.add_argument("--device", default="0")
    run.add_argument("--steps", type=int, default=None)
    run.add_argument("--pool-safety", type=float, default=1.2)
    run.add_argument("--label", default=None, help="a repeat of the same case into logs/.../<run>_<label>")
    commands.add_parser("analyse")
    arguments = parser.parse_args()
    if arguments.command == "analyse":
        return command_analyse(arguments)
    if arguments.command == "cases":
        return command_cases(arguments)
    if arguments.command == "run":
        return command_run(arguments)
    return 1


if __name__ == "__main__":
    sys.exit(main())
