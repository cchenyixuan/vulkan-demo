"""
micropolar_rotor3d.py - the 3-D case of the chapter (Stage 6 of docs/micropolar_design.md, section 4): a cylindrical
rotor of radius R1 = 3 g and length 3 g in a coaxial cylindrical housing of radius 4 g with end gaps g, all walls
w = 0, thesis configuration with numerics.delta_fluid_only: true.

Axis of the rotor: z. The slabs of a chain are cut along x, so the axis lies in the cut planes. Reasons: (1) the
material key rigid_rotation writes v = Omega z^ x (r - centre) on the wall particles (case_loader_v7.py, frozen
with the tag): any other axis needs a change under experiment/v7/utils; (2) the domain is 8 g + walls wide in x
against 5 g + walls in z, so K slabs have more voxel columns each; (3) the flat end faces are lattice planes.

  generate   Geometry (particle files shared by the cases of one size and lattice) and one case directory.
             Every wall surface can be displaced along its normal into the fluid; the lateral surface of the rotor
             and its end faces are two materials and can carry different rotation rates.
  run        Run a case on one slab or a chain; samples of the azimuthal means on an (r, z) grid, the mid-plane
             profiles, the levels; states of the particles near the walls (for the wall sums); the fluid of two
             slabs through the axis and through the mid-plane at the last step (fields).
"""
