def rotor_distance(radius, height, rotor_radius: float, rotor_half_length: float):
    """Signed distance of points (r, z) from the surface of the rotor (positive in the fluid)."""
    outside_radial = radius - rotor_radius
    outside_axial = np.abs(height) - rotor_half_length
    return (np.hypot(np.maximum(outside_radial, 0.0), np.maximum(outside_axial, 0.0))
            + np.minimum(np.maximum(outside_radial, outside_axial), 0.0))


def housing_distance(radius, height, housing_radius: float, housing_half_height: float):
    """Signed distance of points (r, z) from the surface of the housing (positive in the fluid)."""
    inside_radial = housing_radius - radius
    inside_axial = housing_half_height - np.abs(height)
    return np.where((inside_radial >= 0.0) & (inside_axial >= 0.0), np.minimum(inside_radial, inside_axial),
                    -np.hypot(np.maximum(-inside_radial, 0.0), np.maximum(-inside_axial, 0.0)))


def _write_points(path: pathlib.Path, points: np.ndarray, comment: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"# {comment}: {points.shape[0]} particles\n")
        for start in range(0, points.shape[0], 500_000):
            chunk = points[start:start + 500_000]
            handle.write("".join(f"v {x:.7f} {y:.7f} {z:.7f}\n" for x, y, z in chunk))


def command_generate(arguments) -> int:
    from experiment.validation.micropolar_couette import design_parameters
    gap = arguments.gap
    spacing = gap / arguments.gap_in_spacings
    smoothing_length = SUPPORT_OVER_SPACING * spacing
    wall_thickness = WALL_LAYERS * spacing
    nominal_rotor_radius = arguments.rotor_radius_in_gaps * gap
    nominal_rotor_half_length = 0.5 * arguments.rotor_length_in_gaps * gap
    nominal_housing_radius = nominal_rotor_radius + gap
    nominal_housing_half_height = nominal_rotor_half_length + arguments.end_gap_in_gaps * gap
    # every wall surface displaced along its normal into the fluid
    rotor_radius = nominal_rotor_radius + arguments.rotor_lateral_displacement * spacing
    rotor_half_length = nominal_rotor_half_length + arguments.rotor_end_displacement * spacing
    housing_radius = nominal_housing_radius - arguments.housing_lateral_displacement * spacing
    housing_half_height = nominal_housing_half_height - arguments.housing_end_displacement * spacing

    wall_speed = arguments.wall_speed
    rotation_rate = wall_speed / nominal_rotor_radius * arguments.lateral_rate_factor
    end_rotation_rate = wall_speed / nominal_rotor_radius * arguments.end_rate_factor
    far_viscosity = wall_speed * gap / arguments.reynolds
    speed_of_sound = wall_speed / arguments.mach
    micropolar = arguments.coupling_ratio is not None
    if micropolar:
        micropolar_length = gap / (2.0 * arguments.gap_over_two_lengths)
        design = design_parameters(far_viscosity, arguments.coupling_ratio, micropolar_length)
    else:
        design = {"viscosity": far_viscosity, "viscosity_transfer": 0.0, "coupling": 0.0,
                  "viscosity_rotation": 0.0, "micro_inertia": 0.0}
    limits = design
    if arguments.step_from_coupling_ratio is not None:
        limits = design_parameters(far_viscosity, arguments.step_from_coupling_ratio,
                                   gap / (2.0 * arguments.step_from_gap_over_two_lengths))
    dt_acoustic = arguments.cfl * smoothing_length / speed_of_sound
    dt_viscous = arguments.step_number * smoothing_length ** 2 / max(limits["viscosity"], design["viscosity"])
    dt_angular = (arguments.step_number_angular * smoothing_length ** 2
                  / (limits["viscosity_rotation"] / limits["micro_inertia"])
                  if limits["micro_inertia"] > 0.0 else float("inf"))
    timestep = min(dt_acoustic, dt_viscous, dt_angular)
    governing = {dt_acoustic: "acoustic", dt_viscous: "viscous", dt_angular: "angular diffusion"}[timestep]
    end_time = arguments.end_time_factor * gap ** 2 / far_viscosity
    steps = int(np.ceil(end_time / timestep / 1000.0)) * 1000

    out_dir = (_REPO_ROOT / arguments.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    geometry_dir = (_REPO_ROOT / arguments.geometry).resolve()
    geometry_meta = {
        "spacing": spacing, "rotor_radius": rotor_radius, "rotor_half_length": rotor_half_length,
        "housing_radius": housing_radius, "housing_half_height": housing_half_height,
        "wall_layers": WALL_LAYERS, "lattice_offset": list(arguments.lattice_offset),
        "lattice_angle": arguments.lattice_angle, "frame_margin": arguments.frame_margin}
    geometry_file = geometry_dir / "geometry.json"
    if geometry_file.exists():
        stored = json.loads(geometry_file.read_text(encoding="utf-8"))
        stored.setdefault("frame_margin", 2.0)                 # the first geometries of the stage
        if any(abs(stored[key] - value) > 1e-12 if isinstance(value, float) else stored[key] != value
               for key, value in geometry_meta.items()):
            sys.exit(f"{geometry_dir} holds another geometry: {stored}")
        counts = stored["counts"]
        print(f"[rotor3d] geometry {geometry_dir.name}: reused")
    else:
        geometry_dir.mkdir(parents=True, exist_ok=True)
        # The frame fixes the voxel grid (its lower corner is the origin, the voxels are h = 4 dx wide). With a
        # margin of a whole number of spacings a lattice plane lies exactly on every fourth voxel boundary, and so
        # on a cut of a chain: the first step then moves a whole plane of fluid particles (thousands in 3-D) across
        # the cut at once and overflows the migrant region and the departed pool. A margin of 2.25 dx keeps every
        # lattice plane (offset 0 or 0.5 dx) a quarter of a spacing from the boundaries.
        half_extent = housing_radius + wall_thickness + arguments.frame_margin * spacing
        half_height = housing_half_height + wall_thickness + arguments.frame_margin * spacing
        count_xy = int(np.ceil(half_extent / spacing)) + 2
        count_z = int(np.ceil(half_height / spacing)) + 2
        index_xy = np.arange(-count_xy, count_xy + 1, dtype=np.float64)
        index_z = np.arange(-count_z, count_z + 1, dtype=np.float64) + arguments.lattice_offset[2]
        angle = np.radians(arguments.lattice_angle)
        parts = {"domain": [], "rotor_lateral": [], "rotor_end": [], "housing": []}
        grid_x, grid_y = np.meshgrid(index_xy + arguments.lattice_offset[0], index_xy + arguments.lattice_offset[1],
                                     indexing="ij")
        plane_x = spacing * (np.cos(angle) * grid_x - np.sin(angle) * grid_y).ravel()
        plane_y = spacing * (np.sin(angle) * grid_x + np.cos(angle) * grid_y).ravel()
        plane_radius = np.hypot(plane_x, plane_y)
        near = plane_radius < housing_radius + wall_thickness            # nothing beyond the housing shell
        plane_x, plane_y, plane_radius = plane_x[near], plane_y[near], plane_radius[near]
        for level in index_z:                                              # one lattice plane at a time
            height = level * spacing
            if abs(height) >= housing_half_height + wall_thickness:
                continue
            in_rotor = (plane_radius <= rotor_radius) & (abs(height) <= rotor_half_length)
            in_cavity = (plane_radius < housing_radius) & (abs(height) < housing_half_height)
            fluid = in_cavity & ~in_rotor
            shell = in_rotor & ((plane_radius > rotor_radius - wall_thickness)
                                | (abs(height) > rotor_half_length - wall_thickness))
            # a rotor particle belongs to the surface it is nearer to
            lateral = shell & ((rotor_radius - plane_radius) <= (rotor_half_length - abs(height)))
            housing = ~in_cavity
            for name, mask in (("domain", fluid), ("rotor_lateral", lateral), ("rotor_end", shell & ~lateral),
                               ("housing", housing)):
                if mask.any():
                    parts[name].append(np.column_stack([plane_x[mask], plane_y[mask],
                                                        np.full(int(mask.sum()), height)]))
        counts = {}
        for name, chunks in parts.items():
            points = np.concatenate(chunks) if chunks else np.empty((0, 3))
            counts[name] = int(points.shape[0])
            _write_points(geometry_dir / f"{name}.obj", points, f"rotor3d {name}")
        with open(geometry_dir / "frame.obj", "w", encoding="utf-8", newline="\n") as handle:
            handle.write("# rotor3d frame bbox\n")
            for sign_x in (-1.0, 1.0):
                for sign_y in (-1.0, 1.0):
                    for sign_z in (-1.0, 1.0):
                        handle.write(f"v {sign_x * half_extent:.9f} {sign_y * half_extent:.9f} "
                                     f"{sign_z * half_height:.9f}\n")
        geometry_file.write_text(json.dumps({**geometry_meta, "counts": counts}, indent=1), encoding="utf-8")
        print(f"[rotor3d] geometry {geometry_dir.name}: written")

    (out_dir / "materials.yaml").write_text(MATERIALS_TEMPLATE.format(
        density=DENSITY, viscosity=float(design["viscosity"]),
        viscosity_transfer=float(design["viscosity_transfer"]),
        viscosity_rotation=float(design["viscosity_rotation"]), rotation_rate=float(rotation_rate),
        end_rotation_rate=float(end_rotation_rate)), encoding="utf-8", newline="\n")
    total = sum(counts.values())
    if micropolar:
        parameters = (f"Micropolar: K = kappa / mu = {arguments.coupling_ratio:g}, m = g / (2 l) = "
                      f"{arguments.gap_over_two_lengths:g} (l = {micropolar_length / spacing:g} dx); nu = "
                      f"{design['viscosity']:.6e}, nu_t = {design['viscosity_transfer']:.6e}, c = "
                      f"{design['coupling']:.6e}, xi = {design['viscosity_rotation']:.6e}, Theta = "
                      f"{design['micro_inertia']:.6e}; w = 0 on every wall.")
        micropolar_block = f"  micropolar:\n    enabled: true\n    micro_inertia: {design['micro_inertia']!r}\n"
    else:
        parameters = f"Newtonian: nu = nu_inf = {far_viscosity:.6e}."
        micropolar_block = ""
    meta = {
        "title": arguments.title or out_dir.name, "spacing": spacing, "smoothing_length": smoothing_length,
        "gap": gap, "rotor_radius": rotor_radius, "rotor_half_length": rotor_half_length,
        "housing_radius": housing_radius, "housing_half_height": housing_half_height,
        "nominal": {"rotor_radius": nominal_rotor_radius, "rotor_half_length": nominal_rotor_half_length,
                    "housing_radius": nominal_housing_radius, "housing_half_height": nominal_housing_half_height},
        "displacements_in_spacings": {"rotor_lateral": arguments.rotor_lateral_displacement,
                                      "rotor_end": arguments.rotor_end_displacement,
                                      "housing_lateral": arguments.housing_lateral_displacement,
                                      "housing_end": arguments.housing_end_displacement},
        "rotation_rate": rotation_rate, "end_rotation_rate": end_rotation_rate, "wall_speed": wall_speed,
        "far_viscosity": far_viscosity, "reynolds": arguments.reynolds, "mach": arguments.mach,
        "speed_of_sound": speed_of_sound, "micropolar": micropolar, "coupling_ratio": arguments.coupling_ratio,
        "micropolar_length": micropolar_length if micropolar else None,
        **{f"design_{key}": value for key, value in design.items()},
        "epsilon_squared_factor": 1.0e-6, "viscous_form": "laplacian", "wall_boundary": "adami",
        "delta_fluid_only": True,
        "timestep": timestep, "dt_acoustic": dt_acoustic, "dt_viscous": dt_viscous, "dt_angular": dt_angular,
        "governing": governing, "end_time": end_time, "steps": steps, "counts": counts,
        "fluid_count": counts["domain"], "wall_layers": WALL_LAYERS, "geometry": arguments.geometry,
        "lattice_offset": list(arguments.lattice_offset), "lattice_angle": arguments.lattice_angle,
    }
    relative_geometry = pathlib.PurePosixPath(*([".."] * len(pathlib.PurePosixPath(arguments.out).parts)),
                                              *pathlib.PurePosixPath(arguments.geometry).parts)
    (out_dir / "case.yaml").write_text(CASE_TEMPLATE.format(
        title=meta["title"], rotor_radius=rotor_radius, rotor_half_length=rotor_half_length,
        rotation_rate=rotation_rate, end_rotation_rate=end_rotation_rate, housing_radius=housing_radius,
        housing_half_height=housing_half_height, spacing=spacing, smoothing_length=smoothing_length,
        support=SUPPORT_OVER_SPACING, offset_x=arguments.lattice_offset[0], offset_y=arguments.lattice_offset[1],
        offset_z=arguments.lattice_offset[2], angle=arguments.lattice_angle, fluid_count=counts["domain"],
        rotor_lateral_count=counts["rotor_lateral"], rotor_end_count=counts["rotor_end"],
        housing_count=counts["housing"], wall_layers=WALL_LAYERS, parameters=parameters, dt_acoustic=dt_acoustic,
        dt_viscous=dt_viscous, dt_angular=dt_angular, cfl_nominal=arguments.cfl, step_number=arguments.step_number,
        step_number_angular=arguments.step_number_angular, timestep=timestep, governing=governing,
        cfl_effective=timestep * speed_of_sound / smoothing_length, end_time=end_time, steps=steps,
        particle_radius=0.5 * spacing, speed_of_sound=speed_of_sound, micropolar_block=micropolar_block,
        pool_size=int(1.25 * total) + 4096, geometry=str(relative_geometry)), encoding="utf-8", newline="\n")
    (out_dir / "rotor3d.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    print(f"[rotor3d] {out_dir.name}: fluid {counts['domain']:,}, rotor {counts['rotor_lateral']:,} + "
          f"{counts['rotor_end']:,}, housing {counts['housing']:,} (total {total:,}); dt = {timestep:.4e} "
          f"({governing}), {steps:,} steps")
    return 0


